type item struct {
	ID        uuid.UUID  `gorm:"type:uuid;default:gen_random_uuid()" json:"id"`
	TenantID  uuid.UUID  `json:"-"`
	Name      string     `json:"name"`
	Status    string     `gorm:"default:pending" json:"status"`
	DoneAt    *time.Time `json:"done_at"`
	CreatedAt time.Time  `json:"created_at"`
}

func (item) TableName() string { return "__NAME___items" }

// PageKey is the keyset position of this row, satisfying platform.Keyed.
func (i item) PageKey() (time.Time, uuid.UUID) { return i.CreatedAt, i.ID }

type createItemRequest struct {
	Name string `json:"name" binding:"required,max=200"`
}

// listItems returns one page of this tenant's items, newest first.
//
// It returns whatever ApplyKeyset yields — up to Limit+1 rows — and does
// not trim, does not decide has_more and does not build a cursor.
// platform.ListRoute owns all three, so they cannot be got wrong per
// endpoint.
func listItems(deps platform.Deps) platform.ListHandler[item] {
	return func(c *gin.Context, p pagination.Params) ([]item, error) {
		principal, _, ok := authn.TenantPrincipal(c)
		if !ok {
			return nil, nil
		}
		var rows []item
		err := deps.DB.WithTenant(c.Request.Context(), principal.TenantID, func(tx *gorm.DB) error {
			return tenantdb.ApplyKeyset(tx, p).Find(&rows).Error
		})
		return rows, err
	}
}

func (m *Module) Routes(r *platform.Router, deps platform.Deps) {
	g := r.Group("/__NAME__")

	g.POST("/items", PermItemWrite, func(c *gin.Context) {
		p, tenantUUID, ok := authn.TenantPrincipal(c)
		if !ok {
			return
		}
		var req createItemRequest
		if err := c.ShouldBindJSON(&req); err != nil {
			respond.BadRequest(c, err)
			return
		}
		row := item{TenantID: tenantUUID, Name: req.Name}
		err := deps.DB.WithTenant(c.Request.Context(), p.TenantID, func(tx *gorm.DB) error {
			if err := tx.Create(&row).Error; err != nil {
				return err
			}
			data, err := json.Marshal(__NAME__contract.ItemCreatedData{ItemID: row.ID.String(), Name: row.Name})
			if err != nil {
				return err
			}
			return deps.Bus.Publish(tx, __NAME__contract.SubjectItemCreated, events.Event{
				Type: "ItemCreated", Version: 1, TenantID: p.TenantID, Data: data,
			})
		})
		if err != nil {
			respond.InternalErr(c, err, "could not create item")
			return
		}
		respond.Accepted(c, gin.H{"id": row.ID.String()})
	})

	platform.ListRoute(g, "/items", PermItemRead, listItems(deps))

	g.POST("/items/:id/done", PermItemWrite, func(c *gin.Context) {
		p, _, ok := authn.TenantPrincipal(c)
		if !ok {
			return
		}
		id, err := uuid.Parse(c.Param("id"))
		if err != nil {
			respond.NotFound(c, "item")
			return
		}
		var status int
		err = deps.DB.WithTenant(c.Request.Context(), p.TenantID, func(tx *gorm.DB) error {
			var row item
			if err := tx.First(&row, "id = ?", id).Error; err != nil {
				return err
			}
			if row.Status != "pending" {
				status = http.StatusConflict
				return nil
			}
			now := time.Now().UTC()
			result := tx.Model(&item{}).Where("id = ? AND status = 'pending'", id).
				Updates(map[string]any{"status": "done", "done_at": now})
			if result.Error != nil {
				return result.Error
			}
			if result.RowsAffected == 0 {
				// Lost the race to a concurrent transition between the
				// pre-check above and this guarded UPDATE.
				status = http.StatusConflict
				return nil
			}
			data, err := json.Marshal(__NAME__contract.ItemDoneData{ItemID: row.ID.String()})
			if err != nil {
				return err
			}
			return deps.Bus.Publish(tx, __NAME__contract.SubjectItemDone, events.Event{
				Type: "ItemDone", Version: 1, TenantID: p.TenantID, Data: data,
			})
		})
		if errors.Is(err, gorm.ErrRecordNotFound) {
			respond.NotFound(c, "item")
			return
		}
		if err != nil {
			respond.InternalErr(c, err, "could not complete item")
			return
		}
		if status == http.StatusConflict {
			respond.Conflict(c, "already done")
			return
		}
		respond.OK(c, gin.H{"id": id.String(), "status": "done"})
	})
}

