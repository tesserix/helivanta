var do = testutil.Do

func setup(t *testing.T) (*gin.Engine, *tenantdb.DB, context.Context) {
	r, db, _, ctx := testutil.NewHarness(t, testutil.HarnessOptions{
		Tokens: map[string]string{"tokA": testutil.TenantA, "tokB": testutil.TenantB},
		Perms: map[string][]authz.Permission{
			"tokA": {__NAME__.PermItemRead, __NAME__.PermItemWrite},
			"tokB": {__NAME__.PermItemRead, __NAME__.PermItemWrite},
		},
		Modules: []platform.Module{__NAME__.New()},
	})
	return r, db, ctx
}

func TestItemsCreateListIsolation(t *testing.T) {
	r, _, _ := setup(t)

	require.Equal(t, http.StatusAccepted,
		do(r, "POST", "/v1/__NAME__/items", "tokA", `{"name":"First item"}`).Code)
	require.Equal(t, http.StatusBadRequest,
		do(r, "POST", "/v1/__NAME__/items", "tokA", `{}`).Code)
	require.Contains(t, do(r, "GET", "/v1/__NAME__/items", "tokA", "").Body.String(), "First item")
	require.NotContains(t, do(r, "GET", "/v1/__NAME__/items", "tokB", "").Body.String(), "First item")
}

func TestItemDoneTransition(t *testing.T) {
	r, db, ctx := setup(t)

	require.Equal(t, http.StatusAccepted,
		do(r, "POST", "/v1/__NAME__/items", "tokA", `{"name":"Second item"}`).Code)

	var itemID string
	require.Eventually(t, func() bool {
		var resp struct {
			Data []struct {
				ID string `json:"id"`
			} `json:"data"`
		}
		_ = json.Unmarshal(do(r, "GET", "/v1/__NAME__/items", "tokA", "").Body.Bytes(), &resp)
		if len(resp.Data) == 0 {
			return false
		}
		itemID = resp.Data[0].ID
		return true
	}, 20*time.Second, 200*time.Millisecond)

	// Cross-tenant transition probe → 404.
	require.Equal(t, http.StatusNotFound,
		do(r, "POST", "/v1/__NAME__/items/"+itemID+"/done", "tokB", "").Code)

	// Transition succeeds once…
	require.Equal(t, http.StatusOK,
		do(r, "POST", "/v1/__NAME__/items/"+itemID+"/done", "tokA", "").Code)
	require.Contains(t, do(r, "GET", "/v1/__NAME__/items", "tokA", "").Body.String(), `"done"`)

	// …and 409s on repeat.
	require.Equal(t, http.StatusConflict,
		do(r, "POST", "/v1/__NAME__/items/"+itemID+"/done", "tokA", "").Code)

	// item_created hit the outbox.
	require.Eventually(t, func() bool {
		var n int64
		_ = db.WithSystem(ctx, func(tx *gorm.DB) error {
			return tx.Raw(`SELECT count(*) FROM outbox_events
				WHERE subject = 'hms.in.__NAME__.item_created.v1'`).Scan(&n).Error
		})
		return n == 1
	}, 10*time.Second, 200*time.Millisecond)
}

// Exactly one of N concurrent transitions may win. The guarded UPDATE is
// what enforces it — under READ COMMITTED the losers re-evaluate
// "WHERE status = 'pending'" after the winner commits and match zero
// rows. Delete that branch and this test fails; the sequential flow test
// does not, because it never reaches the UPDATE.
func TestConcurrentDoneYieldsExactlyOneWinner(t *testing.T) {
	r, _, _ := setup(t)

	require.Equal(t, http.StatusAccepted,
		do(r, "POST", "/v1/__NAME__/items", "tokA", `{"name":"Concurrent item"}`).Code)

	var itemID string
	require.Eventually(t, func() bool {
		var resp struct {
			Data []struct {
				ID string `json:"id"`
			} `json:"data"`
		}
		_ = json.Unmarshal(do(r, "GET", "/v1/__NAME__/items", "tokA", "").Body.Bytes(), &resp)
		if len(resp.Data) == 0 {
			return false
		}
		itemID = resp.Data[0].ID
		return true
	}, 20*time.Second, 200*time.Millisecond)

	const n = 8
	codes := make(chan int, n)
	var start sync.WaitGroup
	start.Add(1)
	for i := 0; i < n; i++ {
		go func() {
			start.Wait()
			codes <- do(r, "POST", "/v1/__NAME__/items/"+itemID+"/done", "tokA", "").Code
		}()
	}
	start.Done()

	ok, conflict, other := 0, 0, 0
	for i := 0; i < n; i++ {
		switch c := <-codes; c {
		case http.StatusOK:
			ok++
		case http.StatusConflict:
			conflict++
		default:
			other++
			t.Logf("unexpected status %d", c)
		}
	}
	require.Equal(t, 1, ok, "exactly one transition must win")
	require.Equal(t, n-1, conflict, "every loser must get 409")
	require.Zero(t, other)
}
