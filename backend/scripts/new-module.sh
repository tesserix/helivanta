#!/usr/bin/env bash
# Stamps a new standards-compliant backend module under
# internal/modules/<name>, following the medicore/pharmacy shape:
# forced-RLS migration with a status CHECK, respond-helper routes
# (create -> Accepted, list -> OK, guarded transition -> 404/409),
# a published event constant, a consumer stub satisfying the arch-test
# naming rules, and a module_test.go built on testutil.NewHarness.
#
# Usage: ./scripts/new-module.sh <name>   (run from backend/)
set -euo pipefail

NAME="${1:?usage: new-module.sh <name>}"
[[ "$NAME" =~ ^[a-z]+$ ]] || { echo "name must be lowercase letters only (a-z)"; exit 1; }

case "$NAME" in
  package|select|type|func|range|map|chan|go|if|else|for|return|var|const|import|interface|struct|switch|defer|break|continue|fallthrough|goto|default)
    echo "name must not be a Go keyword: $NAME"
    exit 1
    ;;
esac

DIR="internal/modules/$NAME"
[[ -e "$DIR" ]] && { echo "module $NAME already exists"; exit 1; }
mkdir -p "$DIR/contract"

cat > "$DIR/contract/events.go" <<'EOF'
// Package contract is __NAME__'s published event interface. Data only:
// consts, types and vars, importing nothing beyond time and uuid. See
// docs/standards/backend.md and internal/archtest/contract_test.go.
package contract

// SubjectItemCreated is published when an item is created.
const SubjectItemCreated = "hms.in.__NAME__.item_created.v1"

// SubjectItemDone is published when an item transitions to done.
const SubjectItemDone = "hms.in.__NAME__.item_done.v1"

// ItemCreatedData is the v1 payload of SubjectItemCreated.
type ItemCreatedData struct {
	ItemID string `json:"item_id"`
	Name   string `json:"name"`
}

// ItemDoneData is the v1 payload of SubjectItemDone.
type ItemDoneData struct {
	ItemID string `json:"item_id"`
}
EOF

cat > "$DIR/module.go" <<'EOF'
