import { readFile, writeFile, mkdir } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { validateTax } from "./lib/country-tax.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(await readFile(path.join(root, "contracts/country-profiles.json"), "utf8"));
if (
  data.schema_version !== 1 ||
  data.countries.length < 1 ||
  new Set(data.countries.map((p) => p.code)).size !== data.countries.length
)
  throw new Error("Invalid country configuration");
for (const p of data.countries) {
  if (
    !/^[A-Z]{2}$/.test(p.code) ||
    !/^[A-Z]{3}$/.test(p.currency) ||
    !Number.isInteger(p.currency_minor_digits) ||
    p.currency_minor_digits < 0 ||
    p.currency_minor_digits > 3 ||
    !p.timezones.includes(p.timezone) ||
    p.regulatory_policy_status !== "review_required" ||
    !Array.isArray(p.tax_identifier_kinds) ||
    p.tax_identifier_kinds.length === 0 ||
    new Set(p.tax_identifier_kinds).size !== p.tax_identifier_kinds.length ||
    p.tax_identifier_kinds.some((kind) => !/^[a-z][a-z_]{0,39}$/.test(kind))
  )
    throw new Error("Country metadata cannot grant regulatory approval");
  validateTax(p);
  for (const zone of p.timezones) new Intl.DateTimeFormat("en", { timeZone: zone });
  for (const locale of p.locales) {
    if (!["rtl", "ltr"].includes(locale.direction)) throw new Error("Invalid locale direction");
    new Intl.Locale(locale.code);
  }
}
const quoted = JSON.stringify;
let go =
  '// Code generated by scripts/generate-country-profiles.mjs; DO NOT EDIT.\npackage countryprofile\n\nimport "encoding/json"\n\n// Country carries metadata, not regulatory authorization.\ntype Country struct { Code string; Currency string; Timezone string }\n\n// Configuration returns a fresh snapshot of bounded public metadata.\nfunc Configuration() json.RawMessage { return json.RawMessage(' +
  quoted(JSON.stringify(data)) +
  ") }\n\n// Lookup resolves supported metadata without falling back to another country.\nfunc Lookup(code string) (Country,bool) {switch code {\n";
for (const p of data.countries)
  go += `case ${quoted(p.code)}: return Country{Code:${quoted(p.code)},Currency:${quoted(p.currency)},Timezone:${quoted(p.timezone)}},true\n`;
go +=
  "default:return Country{},false\n}}\n\n// ValidTimezone checks the declared country’s supported IANA zones.\nfunc ValidTimezone(code,zone string) bool {switch code {\n";
for (const p of data.countries)
  go += `case ${quoted(p.code)}: return ${p.timezones.map((z) => "zone==" + quoted(z)).join("||")}\n`;
go += "default:return false\n}}\n";
go +=
  "\n// ValidTaxIdentifierKind checks declared metadata, not licence validity.\nfunc ValidTaxIdentifierKind(code,kind string) bool {switch code {\n";
for (const p of data.countries)
  go += `case ${quoted(p.code)}: return ${p.tax_identifier_kinds.map((kind) => "kind==" + quoted(kind)).join("||")}\n`;
go += "default:return false\n}}\n";
go +=
  "\n// Jurisdiction is a place an outlet can be registered; Kind decides the intra-jurisdiction component.\ntype Jurisdiction struct { Code string; Name string; Kind string }\n\n// Source records where scheme structure was copied from.\ntype Source struct { Topic string; URL string; ReviewedAt string }\n\n// TaxScheme is a country's tax structure. It never carries a rate.\ntype TaxScheme struct { Scheme string; RegistrationKind string; ClassificationName string; ClassificationPattern string; Jurisdictions []Jurisdiction; Sources []Source }\n\n// Jurisdiction finds a jurisdiction by code.\nfunc (s TaxScheme) Jurisdiction(code string) (Jurisdiction,bool) { for _, j := range s.Jurisdictions { if j.Code == code { return j, true } }; return Jurisdiction{}, false }\n\n// Tax returns a fresh copy of the country's scheme; false means tax setup is refused there.\nfunc Tax(code string) (TaxScheme,bool) {switch code {\n";
for (const p of data.countries) {
  if (p.tax === null) continue;
  const t = p.tax;
  go += `case ${quoted(p.code)}: return TaxScheme{Scheme:${quoted(t.scheme)},RegistrationKind:${quoted(t.registration_kind)},ClassificationName:${quoted(t.classification.name)},ClassificationPattern:${quoted(t.classification.pattern)},Jurisdictions:[]Jurisdiction{${t.jurisdictions.map((j) => `{${quoted(j.code)},${quoted(j.name)},${quoted(j.kind)}}`).join(",")}},Sources:[]Source{${t.sources.map((s) => `{${quoted(s.topic)},${quoted(s.url)},${quoted(s.reviewed_at)}}`).join(",")}}},true\n`;
}
go += "default:return TaxScheme{},false\n}}\n";
const ts =
  "// Generated by scripts/generate-country-profiles.mjs.\nexport const countryConfiguration=" +
  JSON.stringify(data) +
  ' as const;\nexport type CountryProfile = (typeof countryConfiguration.countries)[number];\nexport function countryProfile(code: string):CountryProfile|undefined {return countryConfiguration.countries.find(profile=>profile.code===code);}\nexport type TaxScheme = NonNullable<CountryProfile["tax"]>;\n/** The country\'s tax structure, or null when tax setup is refused there. */\nexport function taxScheme(code: string):TaxScheme|null {return countryProfile(code)?.tax ?? null;}\n';
const outputs = {
  "backend/pkg/countryprofile/profiles_gen.go": execFileSync("gofmt", [], {
    input: go,
    encoding: "utf8",
  }),
  "packages/api/src/country-profiles.ts": execFileSync(
    "pnpm",
    ["exec", "prettier", "--stdin-filepath", "packages/api/src/country-profiles.ts"],
    { cwd: root, input: ts, encoding: "utf8" },
  ),
};
for (const [file, content] of Object.entries(outputs)) {
  const full = path.join(root, file);
  if (process.argv.includes("--check")) {
    if ((await readFile(full, "utf8")) !== content)
      throw new Error("Stale country contract: " + file);
  } else {
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, content);
  }
}
