import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/emergency-dispatch.json"), "utf8"),
);
const sql = await readFile(
  path.join(root, "backend/internal/modules/emergency/dispatch.sql"),
  "utf8",
);
for (const [field, choices] of [
  ["state", contract.states],
  ["operation", { ...contract.operations, ...contract.worker_operations }],
]) {
  const found = sql.match(new RegExp(`CHECK\\(${field} IN\\(([^)]*)\\)\\)`));
  if (
    !found ||
    JSON.stringify(found[1].replaceAll("'", "").split(",")) !== JSON.stringify(Object.keys(choices))
  ) {
    throw new Error(`Dispatch SQL ${field} vocabulary differs from the shared contract`);
  }
}
const models = emitModels(contract.models);
const capabilitySql = Object.entries(contract.capabilities).flatMap(([actual, required]) =>
  required.map((choice) => `('${actual.replaceAll("'", "''")}','${choice.replaceAll("'", "''")}')`),
);
const sqlFunction = `-- Generated by scripts/generate-emergency-dispatch.mjs.\nCREATE FUNCTION emergency_class_supports(actual text,required text) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$ SELECT EXISTS(SELECT 1 FROM (VALUES ${capabilitySql.join(",")}) allowed(actual_class,required_class) WHERE actual_class=actual AND required_class=required) $$;\n`;
const go =
  '// Code generated by scripts/generate-emergency-dispatch.mjs; DO NOT EDIT.\npackage emergency\nimport "github.com/google/uuid"\n' +
  models.go +
  `\nconst dispatchContractSchema=${JSON.stringify(sqlFunction)};\n`;
const ts =
  '// Generated by scripts/generate-emergency-dispatch.mjs.\nimport { z } from "zod";\n' +
  `export const EMERGENCY_DISPATCH_CAPABILITIES=${JSON.stringify(contract.capabilities)} as const;\n` +
  `export const EMERGENCY_DISPATCH_STATES=${JSON.stringify(contract.states)} as const;\n` +
  `export const EMERGENCY_DISPATCH_OPERATIONS=${JSON.stringify(contract.operations)} as const;\n` +
  models.ts;
await writeGenerated(
  root,
  "backend/internal/modules/emergency/dispatch_types.go",
  go,
  "packages/api/src/emergency-dispatch-contract.ts",
  ts,
  "emergency dispatch",
);
