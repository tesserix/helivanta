import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(
  await readFile(path.join(root, "contracts/manual-person-identity.json"), "utf8"),
);
if (source.resource_uuid_version !== 7) {
  throw new Error("Manual identity resources require UUIDv7");
}
for (const fields of Object.values(source.models)) {
  for (const field of fields) {
    if (
      field.type === "uuid" &&
      field.name !== "tenant_id" &&
      field.uuid_version !== source.resource_uuid_version
    ) {
      throw new Error(`Inconsistent identity reference ${field.name}`);
    }
  }
}
const timeRules = JSON.parse(
  await readFile(path.join(root, "contracts/staff-governance.json"), "utf8"),
);
if (timeRules.time_precision_digits !== 6)
  throw new Error("Manual identity storage requires reviewed PostgreSQL time precision");
const models = emitModels(source.models);
for (const [name, fields] of Object.entries(source.models)) {
  const checks = fields.flatMap((field) => {
    const value = `value.${field.name}`;
    const issue = `ctx.addIssue({code:"custom",path:[${JSON.stringify(field.name)}],message:"Use a valid identity record."});`;
    if (field.uuid_version) {
      return [
        `if(${field.nullable ? `${value}!==null&&` : ""}!/^[0-9a-f]{8}-[0-9a-f]{4}-${field.uuid_version}[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(${value}))${issue}`,
      ];
    }
    if (field.type === "time") {
      return [
        `if(!new RegExp(${JSON.stringify(timeRules.instant_pattern)}).test(${value}))${issue}`,
      ];
    }
    if (field.format === "manual_identity_text") {
      return [`if(${value}.trim().length===0)${issue}`];
    }
    return [];
  });
  if (checks.length) {
    const declaration = new RegExp(
      `(${name}Contract=z.object\\(\\{[\\s\\S]*?\\}\\)\\.strict\\(\\))`,
    );
    if (!declaration.test(models.ts)) throw new Error(`Missing model ${name}`);
    models.ts = models.ts.replace(
      declaration,
      `$1.superRefine((value,ctx)=>{${checks.join("\n")}})`,
    );
  }
}
const maximum = (model, field) => source.models[model].find((value) => value.name === field).max;
const rules = `
const manualIdentitySourceVersion=${source.version}
var manualIdentityImportInstantFields=[]string{${source.models.ManualIdentitySourceImport.filter(
  (field) => field.type === "time",
)
  .map((field) => JSON.stringify(field.name))
  .join(",")}}
const manualIdentityResourceUUIDVersion=${source.resource_uuid_version}
const manualIdentityRootMinimum=${source.models.ManualIdentitySourceImport.find((field) => field.name === "roots").min}
const manualIdentityRootMaximum=${maximum("ManualIdentitySourceImport", "roots")}
const manualIdentityAccountMaximum=${maximum("ManualIdentityRootPerson", "accounts")}
const manualIdentityImportReasonMaximum=${maximum("ManualIdentitySourceImport", "reason")}
const manualIdentityCaseReasonMaximum=${maximum("ManualIdentityCaseInput", "reason")}
const manualIdentityExaminationReasonMaximum=${maximum("ManualIdentityExaminationInput", "reason")}
const manualIdentityDecisionReasonMaximum=${maximum("ManualIdentityDecisionInput", "reason")}
const manualIdentityDisplayNameMaximum=${maximum("ManualIdentitySourceImport", "display_name")}
const manualIdentityMaxVersion=${maximum("ManualIdentityRootAccount", "expected_membership_epoch")}
const manualIdentityBlankCharacters=${JSON.stringify(source.blank_text_characters).replace(/[^\x20-\x7e]/gu, (char) => "\\u" + char.charCodeAt(0).toString(16).padStart(4, "0"))}
`;

await writeGenerated(
  root,
  "backend/internal/modules/iam/manual_person_types_generated.go",
  '// Code generated by scripts/generate-manual-person-identity.mjs; DO NOT EDIT.\npackage iam\nimport("time";"github.com/google/uuid")\n' +
    models.go +
    rules,
  "packages/api/src/manual-person-identity-contract.ts",
  '// Generated by scripts/generate-manual-person-identity.mjs. Identity assurance confers no clinical authority.\nimport {z} from "zod";\n' +
    models.ts,
  "manual person identity",
);

const sqlFile = "backend/internal/modules/iam/manual_person_source_contract_generated.sql";
const limits = {
  display_name: maximum("ManualIdentitySourceImport", "display_name"),
  reason: maximum("ManualIdentitySourceImport", "reason"),
  root_minimum: source.models.ManualIdentitySourceImport.find((field) => field.name === "roots")
    .min,
  root_maximum: maximum("ManualIdentitySourceImport", "roots"),
  account_maximum: maximum("ManualIdentityRootPerson", "accounts"),
  max_version: maximum("ManualIdentityRootAccount", "expected_membership_epoch"),
};
const sql = `-- Code generated by scripts/generate-manual-person-identity.mjs; DO NOT EDIT.
CREATE FUNCTION iam_manual_identity_limit(rule text) RETURNS bigint LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE rule ${Object.entries(limits)
   .map(([key, value]) => `WHEN '${key}' THEN ${value}::bigint`)
   .join(" ")} END
$$;
CREATE FUNCTION iam_manual_identity_instant(value timestamptz) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
 SELECT value>'${timeRules.instant_bounds[0]}'::timestamptz AND value<='${timeRules.instant_bounds[1]}'::timestamptz
$$;
`;
if (process.argv.includes("--check")) {
  if ((await readFile(path.join(root, sqlFile), "utf8")) !== sql)
    throw new Error(`Generated manual identity SQL is stale: ${sqlFile}`);
} else await writeFile(path.join(root, sqlFile), sql);
