import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/operating-assignments.json"), "utf8"),
);
const identity = [];
for (const ref of contract.identity_fields) {
  const source = JSON.parse(await readFile(path.join(root, "contracts", ref.file), "utf8"));
  const field = source.models[ref.model]?.find((value) => value.name === ref.field);
  if (!field)
    throw new Error(`Unknown canonical identity field ${ref.file}:${ref.model}:${ref.field}`);
  identity.push({
    ...field,
    name: ref.as ?? field.name,
    ...(ref.min !== undefined ? { min: ref.min } : {}),
    ...(ref.max !== undefined ? { max: ref.max } : {}),
  });
}
const models = emitModels({ OperatingDutyIdentity: identity, ...contract.models });
const quote = (value) => JSON.stringify(value);
const catalog =
  "var operatingDutyTemplates=[]OperatingDutyTemplate{\n" +
  contract.templates
    .map(
      (t) =>
        `{Key:${quote(t.key)},EmployerKind:${quote(t.employer_kind)},Label:${quote(t.label)},Permissions:[]string{${t.permissions.map(quote).join(",")}},MaxValidityHours:${t.max_validity_hours}},`,
    )
    .join("\n") +
  "\n}\n";
const literal = (value) => "'" + value.replaceAll("'", "''") + "'";
const sql = `-- Generated by scripts/generate-operating-assignments.mjs; DO NOT EDIT.\nCREATE FUNCTION iam_operating_template_permissions(template text,kind text)RETURNS jsonb LANGUAGE sql IMMUTABLE STRICT AS $$ SELECT CASE\n${contract.templates.map((t) => `WHEN template=${literal(t.key)}AND kind=${literal(t.employer_kind)}THEN ${literal(JSON.stringify(t.permissions))}::jsonb`).join("\n")}\nELSE NULL END $$;\n`;
const sqlFile = path.join(root, "backend/internal/modules/iam/operating_templates_generated.sql");
if (process.argv.includes("--check")) {
  if ((await readFile(sqlFile, "utf8")) !== sql)
    throw new Error("Generated operating template SQL is stale");
} else await writeFile(sqlFile, sql);

await writeGenerated(
  root,
  "backend/internal/modules/iam/operating_types_generated.go",
  `// Code generated by scripts/generate-operating-assignments.mjs; DO NOT EDIT.\npackage iam\nimport("time";"github.com/google/uuid")\n${models.go}\n${catalog}`,
  "packages/api/src/operating-assignments-contract.ts",
  `// Code generated by scripts/generate-operating-assignments.mjs; DO NOT EDIT.\nimport{z}from"zod";\n${models.ts}\nexport const operatingDutyTemplates: readonly OperatingDutyTemplate[] = ${JSON.stringify(contract.templates)};\n`,
  "Independent operating assignments",
);
