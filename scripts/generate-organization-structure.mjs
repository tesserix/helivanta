import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/organization-structure.json"), "utf8"),
);
const header = "// Code generated by scripts/generate-organization-structure.mjs; DO NOT EDIT.\n";
const models = emitModels(contract.models);
const wire = emitModels({
  ...contract.models,
  ...contract.organization_events,
  ...contract.workforce_events,
});
await writeGenerated(
  root,
  "backend/internal/modules/organization/reference_types.go",
  header + 'package organization\nimport("time";"github.com/google/uuid")\n' + models.go,
  "packages/api/src/organization-structure-contract.ts",
  '// Generated by scripts/generate-organization-structure.mjs.\nimport {z} from "zod";\n' +
    wire.ts,
  "organization structure",
);
for (const [owner, key] of [
  ["organization", "organization_events"],
  ["workforce", "workforce_events"],
]) {
  const output = emitModels(contract[key]);
  const file = `backend/internal/modules/${owner}/contract/organization_reference_generated.go`;
  const source = header + 'package contract\nimport "github.com/google/uuid"\n' + output.go;
  const formatted = execFileSync("gofmt", [], { input: source, encoding: "utf8" });
  if (process.argv.includes("--check")) {
    if ((await readFile(path.join(root, file), "utf8")) !== formatted)
      throw new Error(`Stale organization reference contract: ${file}`);
  } else await writeFile(path.join(root, file), formatted);
}
