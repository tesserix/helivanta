import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/partner-grants.json"), "utf8"),
);
if (!Number.isSafeInteger(contract.maximum_validity_days) || contract.maximum_validity_days < 1)
  throw new Error("Partner grant validity must be bounded");
if (contract.maximum_timestamp_fraction_digits !== 9)
  throw new Error("Partner grant timestamps must retain nanosecond precision");
const models = emitModels(contract.models);
const timestampInputFields = contract.models.PartnerGrantDraftInput.filter(
  (field) => field.type === "time",
).map((field) => field.name);
const uuidChecks = contract.models.PartnerGrantDraftInput.filter((field) => field.uuid_version)
  .map(
    (field) =>
      `if(${field.optional ? `value.${field.name}!==undefined&&` : ""}!/^[0-9a-f]{8}-[0-9a-f]{4}-${field.uuid_version}[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(value.${field.name}))ctx.addIssue({code:"custom",path:[${JSON.stringify(field.name)}],message:"Choose a canonical source record."});`,
  )
  .join("\n");
const refinement = `.superRefine((value,ctx)=>{
${uuidChecks}
for(const field of ${JSON.stringify(timestampInputFields)} as const){const fraction=value[field].match(/\\.(\\d+)/)?.[1];if(fraction&&fraction.length>${contract.maximum_timestamp_fraction_digits})ctx.addIssue({code:"custom",path:[field],message:"Use at most ${contract.maximum_timestamp_fraction_digits} fractional timestamp digits."});}
const start=partnerGrantTimestampNanos(value.valid_from),end=partnerGrantTimestampNanos(value.expires_at);
if(start===undefined||end===undefined||end<=start||end-start>BigInt(${contract.maximum_validity_days})*86400000000000n)ctx.addIssue({code:"custom",path:["expires_at"],message:"Choose a positive validity of at most ${contract.maximum_validity_days} days."});
if(value.recipient_kind==="group"?(!value.recipient_group_id||value.recipient_subject!==undefined):(!value.recipient_subject||value.recipient_group_id!==undefined))ctx.addIssue({code:"custom",path:["recipient_kind"],message:"Choose exactly one named account or hospital team."});
if(value.recipient_subject!==undefined&&!/^[^\\s*#:\\p{Cc}]{1,200}$/u.test(value.recipient_subject))ctx.addIssue({code:"custom",path:["recipient_subject"],message:"Choose a canonical named account."});
if(value.reason.trim()!==value.reason||/\\p{Cc}/u.test(value.reason))ctx.addIssue({code:"custom",path:["reason"],message:"Enter a reason without surrounding whitespace or control characters."});
})`;
const wire = models.ts
  .replace(
    /(export const PartnerGrantDraftInputContract=z.object\(\{[\s\S]*?\}\)\.strict\(\))/,
    "$1" + refinement,
  )
  .replace(
    /(export const PartnerGrantDraftContract=z.object\(\{[\s\S]*?\}\)\.strict\(\))/,
    '$1.superRefine((value,ctx)=>{if(value.operating_access_enabled!==false)ctx.addIssue({code:"custom",path:["operating_access_enabled"],message:"Draft intent cannot authorize trading."});})',
  );
const nonNullableOptionalFields = contract.models.PartnerGrantDraftInput.filter(
  (field) => field.optional && !field.nullable,
).map((field) => field.name);
const uuidInputFields = contract.models.PartnerGrantDraftInput.filter(
  (field) => field.type === "uuid",
).map((field) => field.name);
const enums = Object.fromEntries(
  contract.models.PartnerGrantDraftInput.filter((f) => f.enum).map((f) => [f.name, f.enum]),
);
await writeGenerated(
  root,
  "backend/internal/modules/iam/partner_grant_types_generated.go",
  '// Code generated by scripts/generate-partner-grants.mjs; DO NOT EDIT.\npackage iam\nimport("time";"github.com/google/uuid")\n' +
    models.go +
    `\nconst partnerGrantMaximumValidityDays=${contract.maximum_validity_days}\nconst partnerGrantMaximumTimestampFractionDigits=${contract.maximum_timestamp_fraction_digits}\nvar partnerGrantTimestampInputFields=[]string{${timestampInputFields.map((name) => JSON.stringify(name)).join(",")}}\nvar partnerGrantInputEnums=map[string][]string{` +
    Object.entries(enums)
      .map(
        ([k, values]) =>
          `${JSON.stringify(k)}:{${values.map((v) => JSON.stringify(v)).join(",")}},`,
      )
      .join("\n") +
    "}\nvar partnerGrantNonNullableOptionalFields=[]string{" +
    nonNullableOptionalFields.map((name) => JSON.stringify(name)).join(",") +
    "}\n",
  "packages/api/src/partner-grant-contract.ts",
  '// Generated by scripts/generate-partner-grants.mjs.\nimport {z} from "zod";\n' +
    `export function partnerGrantTimestampNanos(value:string):bigint|undefined{
const match=value.match(/T\\d{2}:\\d{2}:\\d{2}(?:\\.(\\d{1,${contract.maximum_timestamp_fraction_digits}}))?(?:Z|[+-]\\d{2}:\\d{2})$/);
const millis=Date.parse(value);
if(!match||!Number.isFinite(millis))return undefined;
return BigInt(millis)*1000000n+BigInt((match[1]??"").padEnd(${contract.maximum_timestamp_fraction_digits},"0").slice(3));
}\n` +
    wire +
    `\nexport const partnerGrantUUIDInputFields: ReadonlySet<string> = new Set(${JSON.stringify(uuidInputFields)});\n`,
  "Partner grant preparation",
);
