import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/partner-groups.json"), "utf8"),
);
const models = emitModels(contract.models);
if (!Number.isSafeInteger(contract.maximum_validity_days) || contract.maximum_validity_days < 1)
  throw new Error("Partner group validity must be bounded");
let wire = models.ts;
for (const [name, fields] of Object.entries(contract.models)) {
  const checks = [];
  if (
    fields.some((field) => field.name === "valid_from") &&
    fields.some((field) => field.name === "expires_at")
  )
    checks.push(
      `const duration=Date.parse(value.expires_at)-Date.parse(value.valid_from);if(!(duration>0&&duration<=${contract.maximum_validity_days}*86400000))ctx.addIssue({code:"custom",path:["expires_at"],message:"Choose a positive validity of at most ${contract.maximum_validity_days} days."});`,
    );
  if (name === "PartnerMemberCommandInput") {
    const attestations = contract.member_approval_required_attestations;
    if (
      !Array.isArray(attestations) ||
      attestations.length !== 2 ||
      new Set(attestations).size !== 2 ||
      attestations.some(
        (field) =>
          !fields.some(
            (definition) =>
              definition.name === field && definition.type === "bool" && definition.optional,
          ),
      )
    )
      throw new Error("Membership approval requires two explicit optional boolean attestations");
    for (const field of attestations)
      checks.push(
        `if(value.operation==="approve"&&value.${field}!==true)ctx.addIssue({code:"custom",path:[${JSON.stringify(field)}],message:"Confirm the current source and purpose eligibility before approval."});`,
      );
  }
  for (const field of fields) {
    if (field.uuid_version)
      checks.push(
        `if(!/^[0-9a-f]{8}-[0-9a-f]{4}-${field.uuid_version}[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(value.${field.name}))ctx.addIssue({code:"custom",path:[${JSON.stringify(field.name)}],message:"Choose a canonical group record."});`,
      );
    if (Object.hasOwn(field, "literal"))
      checks.push(
        `if(value.${field.name}!==${JSON.stringify(field.literal)})ctx.addIssue({code:"custom",path:[${JSON.stringify(field.name)}],message:${JSON.stringify(field.literal_error ?? (field.name === "external_access_enabled" ? "A team alone does not grant external access." : "Use the published membership policy."))}});`,
      );
  }
  if (checks.length)
    wire = wire.replace(
      new RegExp(`(export const ${name}Contract=z.object\\(\\{[\\s\\S]*?\\}\\)\\.strict\\(\\))`),
      `$1.superRefine((value,ctx)=>{${checks.join("")}})`,
    );
}
await writeGenerated(
  root,
  "backend/internal/modules/iam/partner_group_types_generated.go",
  '// Code generated by scripts/generate-partner-groups.mjs; DO NOT EDIT.\npackage iam\nimport("time";"github.com/google/uuid")\n' +
    models.go,
  "packages/api/src/partner-group-contract.ts",
  '// Generated by scripts/generate-partner-groups.mjs.\nimport {z} from "zod";\n' + wire,
  "Partner groups",
);

for (const [moduleName, modelName, constant, subject] of [
  [
    "iam",
    "PartnerGroupHospitalScopeRequestedData",
    "SubjectPartnerGroupHospitalScopeRequested",
    contract.scope_request_subject,
  ],
  [
    "workforce",
    "PartnerGroupHospitalScopeObservedData",
    "SubjectPartnerGroupHospitalScopeObserved",
    contract.scope_observation_subject,
  ],
]) {
  const file = path.join(
    root,
    `backend/internal/modules/${moduleName}/contract/partner_group_scope_generated.go`,
  );
  const generated = execFileSync("gofmt", [], {
    input:
      '// Code generated by scripts/generate-partner-groups.mjs; DO NOT EDIT.\npackage contract\nimport "github.com/google/uuid"\nconst ' +
      constant +
      "=" +
      JSON.stringify(subject) +
      "\n" +
      (moduleName === "iam"
        ? "const SubjectPartnerGroupChanged=" +
          JSON.stringify(contract.group_changed_subject) +
          "\nconst SubjectPartnerGroupMemberChanged=" +
          JSON.stringify(contract.member_changed_subject) +
          "\n"
        : "") +
      emitModels({
        [modelName]: contract.events[modelName],
        ...(moduleName === "iam"
          ? {
              PartnerGroupChangedData: contract.events.PartnerGroupChangedData,
              PartnerGroupMemberChangedData: contract.events.PartnerGroupMemberChangedData,
            }
          : {}),
      }).go,
    encoding: "utf8",
  });
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== generated)
      throw new Error("Stale partner group event contract");
  } else await writeFile(file, generated);
}
