import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { models } = JSON.parse(await readFile(path.join(root, "contracts/pharmacy.json"), "utf8"));
const countryMetadata = JSON.parse(
  await readFile(path.join(root, "contracts/country-profiles.json"), "utf8"),
);
const names = Object.fromEntries(models.map((model) => [model.name, model.schema]));
const pascal = (name) =>
  name
    .split("_")
    .map((part) =>
      part === "sku"
        ? "SKU"
        : part === "id"
          ? "ID"
          : part === "mrp"
            ? "MRP"
            : part[0].toUpperCase() + part.slice(1),
    )
    .join("");
let go =
  '// Code generated by scripts/generate-pharmacy-contract.mjs; DO NOT EDIT.\npackage pharmacy\n\nimport "github.com/google/uuid"\n\n';
let ts =
  '// Generated by scripts/generate-pharmacy-contract.mjs.\nimport { z } from "zod";\n\nconst identifier=z.string().uuid().regex(/^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i,"Choose a valid record.");\n';
for (const model of models) {
  go += `type ${model.name} struct{\n`;
  ts += `export const ${model.schema}=${model.embed ? names[model.embed] + ".extend" : "z.object"}({\n`;
  for (const originalField of model.fields) {
    const field = originalField.country_profile
      ? { ...originalField, enum: countryMetadata.countries.map((p) => p.code) }
      : originalField;
    const array = field.type.startsWith("[]");
    const base = array ? field.type.slice(2) : field.type;
    let goType = base === "uuid" ? "uuid.UUID" : base;
    if (array) goType = "[]" + goType;
    if (field.pointer || field.optional) goType = "*" + goType;
    const validation = [];
    if (
      !field.optional &&
      ((base === "string" && field.min > 0) ||
        base === "uuid" ||
        array ||
        field.pointer ||
        field.nonzero)
    )
      validation.push("required");
    if (field.optional) validation.push("omitempty");
    if (field.min !== undefined) validation.push(`min=${field.min}`);
    if (field.max !== undefined) validation.push(`max=${field.max}`);
    if (field.enum) validation.push(`required,oneof=${field.enum.join(" ")}`);
    if (array) validation.push("dive");
    const tags = [`json:"${field.name}"`];
    if (validation.length) tags.push(`binding:"${validation.join(",")}"`);
    if (field.gorm) tags.push(`gorm:"${field.gorm}"`);
    go += `${pascal(field.name)} ${goType} \`${tags.join(" ")}\`\n`;
    let schema =
      names[base] ??
      (base === "uuid" ? "identifier" : base === "string" ? "z.string()" : "z.number().int()");
    if (field.uuid_any)
      schema =
        'z.string().uuid().refine(value=>value!=="00000000-0000-0000-0000-000000000000","Choose a valid hospital reference.")';
    if (field.enum) schema = `z.enum(${JSON.stringify(field.enum)})`;
    if (array) schema = `z.array(${schema})`;
    if (field.trim) schema += ".trim()";
    if (field.upper) schema += ".toUpperCase()";
    if (field.min !== undefined) schema += `.min(${field.min})`;
    if (field.max !== undefined) schema += `.max(${field.max})`;
    if (field.pattern)
      schema += `.regex(new RegExp(${JSON.stringify(field.pattern)}),"Use the required format.")`;
    if (field.format === "date") schema += '.date("Use a full valid date.")';
    if (field.nonzero) schema += '.refine(value=>value!==0,"Quantity cannot be zero.")';
    if (field.optional) schema += ".nullable().optional()";
    ts += `${field.name}:${schema},\n`;
  }
  if (model.embed) go += `${model.embed}\n`;
  go += "}\n\n";
  ts += "}).strict();\n\n";
}
const outputs = {
  "backend/internal/modules/pharmacy/input_types.go": execFileSync("gofmt", [], {
    input: go,
    encoding: "utf8",
  }),
  "packages/api/src/pharmacy-contract.ts": execFileSync(
    "pnpm",
    ["exec", "prettier", "--stdin-filepath", "packages/api/src/pharmacy-contract.ts"],
    { cwd: root, input: ts, encoding: "utf8" },
  ),
};
for (const [file, content] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path.join(root, file), "utf8")) !== content)
      throw new Error(`Generated pharmacy contract is stale: ${file}`);
  } else await writeFile(path.join(root, file), content);
}
