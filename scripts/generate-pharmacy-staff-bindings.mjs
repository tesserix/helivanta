import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/pharmacy-staff-bindings.json"), "utf8"),
);
const models = emitModels(contract.models);
const events = emitModels(contract.events);
const wireModels = emitModels({ ...contract.models, ...contract.events });
const wire = wireModels.ts
  .replace(
    /(export const StaffDepartmentBindingProposalInputContract=z.object\(\{[\s\S]*?\}\)\.strict\(\))/,
    '$1.superRefine((value,ctx)=>{if((value.replaces_binding_id===null)!==(value.replaces_binding_version===null))ctx.addIssue({code:"custom",path:["replaces_binding_id"],message:"Choose the exact binding and its current version together."});})',
  )
  .replace(
    /(export const StaffDepartmentBindingCommandInputContract=z.object\(\{[\s\S]*?\}\)\.strict\(\))/,
    '$1.superRefine((value,ctx)=>{if(value.attest_department_responsibility!==(value.operation==="approve"))ctx.addIssue({code:"custom",path:["attest_department_responsibility"],message:"Attest department responsibility only when approving the relationship."});})',
  );
await writeGenerated(
  root,
  "backend/internal/modules/pharmacy/staff_department_binding_types.go",
  '// Code generated by scripts/generate-pharmacy-staff-bindings.mjs; DO NOT EDIT.\npackage pharmacy\nimport("time";"github.com/google/uuid")\n' +
    models.go,
  "packages/api/src/pharmacy-staff-binding-contract.ts",
  '// Generated by scripts/generate-pharmacy-staff-bindings.mjs.\nimport {z} from "zod";\n' + wire,
  "Pharmacy Staff department binding",
);
const eventFile =
  "backend/internal/modules/pharmacy/contract/staff_department_binding_events_generated.go";
const eventSource = execFileSync("gofmt", [], {
  input:
    '// Code generated by scripts/generate-pharmacy-staff-bindings.mjs; DO NOT EDIT.\npackage contract\nimport "github.com/google/uuid"\nconst SubjectStaffDepartmentBindingChanged=' +
    JSON.stringify(contract.subject) +
    "\n" +
    events.go,
  encoding: "utf8",
});
if (process.argv.includes("--check")) {
  if ((await readFile(path.join(root, eventFile), "utf8")) !== eventSource)
    throw new Error("Stale Pharmacy Staff binding event contract");
} else await writeFile(path.join(root, eventFile), eventSource);
