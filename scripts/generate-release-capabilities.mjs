import { readFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
import { validateReleaseManifest } from "./lib/release-capabilities.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(
  await readFile(path.join(root, "contracts/release-capabilities.json"), "utf8"),
);
const inventory = JSON.parse(
  await readFile(path.join(root, "docs/api/reference/inventory.json"), "utf8"),
);
const declared = [
  ...inventory.modules.flatMap((module) => module.routes),
  ...Object.keys(inventory.unauthenticated_routes).map((key) => {
    const separator = key.indexOf(" ");
    return { method: key.slice(0, separator), path: key.slice(separator + 1) };
  }),
];
validateReleaseManifest(manifest, declared);

if (process.argv.includes("--check")) {
  const declaredKeys = new Set(declared.map((route) => `${route.method} ${route.path}`));
  for (const route of manifest.routes) {
    if (!declaredKeys.has(`${route.method} ${route.path}`))
      throw new Error(`Unregistered release route: ${route.method} ${route.path}`);
  }
  const workspace = path.join(root, "apps/shell/app/(workspace)");
  const pages = new Set(manifest.pages.map((page) => page.path));
  for (const entry of await readdir(workspace, { recursive: true })) {
    if (!entry.endsWith("page.tsx")) continue;
    const page = `/${path.dirname(entry)}`.replace(/\[([^\]]+)\]/g, ":$1");
    if (!pages.has(page)) throw new Error(`Unclassified workspace page: ${page}`);
  }
}

const models = emitModels(manifest.models);
const definitions = manifest.capabilities
  .map(
    (capability) =>
      `{Key:${JSON.stringify(capability.key)},Eligible:${capability.eligible},Dependencies:[]string{${capability.dependencies.map(JSON.stringify).join(",")}}}`,
  )
  .join(",\n");
const bindings = manifest.routes
  .map(
    (route) =>
      `${JSON.stringify(`${route.method} ${route.path}`)}:${JSON.stringify(route.capability)}`,
  )
  .join(",\n");

await writeGenerated(
  root,
  "backend/internal/release/manifest_generated.go",
  `// Code generated by scripts/generate-release-capabilities.mjs; DO NOT EDIT.
package release
import ("time"; "github.com/google/uuid")
const PolicyVersion=${JSON.stringify(manifest.policy_version)}
var definitions=[]Definition{${definitions},}
var routeCapabilities=map[string]string{${bindings},}
${models.go}`,
  "packages/api/src/release-capabilities-contract.ts",
  `// Generated by scripts/generate-release-capabilities.mjs.
import { z } from "zod";
export const releaseDefinitions=${JSON.stringify(manifest.capabilities)} as const;
export const releasePages=${JSON.stringify(manifest.pages)} as const;
export const releasePanels=${JSON.stringify(manifest.panels)} as const;
${models.ts}`,
  "release capabilities",
);
