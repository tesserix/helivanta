import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(await readFile(path.join(root, "contracts/staff-access.json"), "utf8"));
const templates = contract.templates;
if (!Array.isArray(templates) || templates.length === 0)
  throw new Error("Missing staff access templates");
const keys = new Set();
for (const template of templates) {
  if (
    !/^workforce\.[a-z_]+\.v[1-9][0-9]*$/.test(template.key) ||
    keys.has(template.key) ||
    !["leave", "identity"].includes(template.family) ||
    !template.name ||
    !template.description ||
    !Array.isArray(template.permissions) ||
    template.permissions.length !== 1 ||
    !template.permissions.every((permission) => /^workforce\.[a-z_.]+$/.test(permission))
  ) {
    throw new Error("Invalid declared staff access template");
  }
  keys.add(template.key);
}
for (const fields of Object.values(contract.models)) {
  for (const field of fields) {
    if (field.enum_ref === "templates") field.enum = [...keys];
  }
}
const models = emitModels(contract.models);
await writeGenerated(
  root,
  "backend/internal/modules/iam/staff_access_generated.go",
  '// Code generated by scripts/generate-staff-access.mjs; DO NOT EDIT.\npackage iam\nimport("time";"github.com/google/uuid")\n' +
    models.go,
  "packages/api/src/staff-access-contract.ts",
  '// Generated by scripts/generate-staff-access.mjs.\nimport {z} from "zod";\n' + models.ts,
  "staff access",
);

for (const [module, name, source, filename] of [
  ["iam", "AssignmentScopeRequestedData", "ScopeRequest", "assignment_scope_generated.go"],
  [
    "iam",
    "AssignmentProjectionRequestedData",
    "ProjectionRequest",
    "assignment_projection_generated.go",
  ],
  ["workforce", "AssignmentScopeVerifiedData", "ScopeResult", "assignment_scope_generated.go"],
]) {
  const file = path.join(root, `backend/internal/modules/${module}/contract/${filename}`);
  const code =
    '// Code generated by scripts/generate-staff-access.mjs; DO NOT EDIT.\npackage contract\nimport "github.com/google/uuid"\n' +
    emitModels({ [name]: contract.models[source] }).go;
  const formatted = execFileSync("gofmt", [], { input: code, encoding: "utf8" });
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== formatted) throw new Error(`Stale contract: ${file}`);
  } else await writeFile(file, formatted);
}

async function writeTemplateArtifact(relative, content) {
  const file = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== content)
      throw new Error(`Generated staff templates drift: ${relative}`);
  } else await writeFile(file, content);
}
const definitions = templates
  .map(
    (template) =>
      `{Key:${JSON.stringify(template.key)},Name:${JSON.stringify(template.name)},Description:${JSON.stringify(template.description)},Family:${JSON.stringify(template.family)},Permissions:[]string{${template.permissions.map((p) => JSON.stringify(p)).join(",")}}}`,
  )
  .join(",");
const go = `// Code generated by scripts/generate-staff-access.mjs; DO NOT EDIT.
package iam
import "github.com/tesserix/helivanta/pkg/authz"
func staffAccessTemplates() []TemplateDefinition { return []TemplateDefinition{${definitions}} }
func staffAccessTemplatePermissions(key string) []authz.Permission {
 for _, template := range staffAccessTemplates() { if template.Key == key { permissions:=make([]authz.Permission,len(template.Permissions)); for i,p:=range template.Permissions {permissions[i]=authz.Permission(p)}; return permissions } }
 return nil
}
func staffAccessPermissionSupported(permission authz.Permission) bool {
 for _, template := range staffAccessTemplates() { for _, candidate := range template.Permissions { if string(permission) == candidate { return true } } }
 return false
}
`;
await writeTemplateArtifact(
  "backend/internal/modules/iam/staff_access_templates_generated.go",
  execFileSync("gofmt", [], { input: go, encoding: "utf8" }),
);
const ts =
  "// Generated by scripts/generate-staff-access.mjs.\nexport const staffAccessTemplates=" +
  JSON.stringify(templates) +
  " as const;\n";
await writeTemplateArtifact(
  "packages/api/src/staff-access-templates.ts",
  execFileSync(
    "pnpm",
    ["exec", "prettier", "--stdin-filepath", "packages/api/src/staff-access-templates.ts"],
    {
      cwd: root,
      input: ts,
      encoding: "utf8",
    },
  ),
);
const quote = (value) => "'" + value.replaceAll("'", "''") + "'";
const activation = await readFile(
  path.join(root, "backend/internal/modules/iam/assignment_activation.sql"),
  "utf8",
);
const snapshot = activation.match(
  /CREATE OR REPLACE FUNCTION iam_assignment_snapshot_record\(\)[\s\S]*?\$\$;/,
)?.[0];
const oldPermissions = `'["workforce.leave.approve"]'::jsonb`;
if (!snapshot || !snapshot.includes(oldPermissions))
  throw new Error("Missing current assignment snapshot definition");
const sql = `-- Generated by scripts/generate-staff-access.mjs; DO NOT EDIT.
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='60s';
CREATE FUNCTION iam_assignment_template_permissions(key text) RETURNS jsonb LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE key ${templates.map((template) => "WHEN " + quote(template.key) + " THEN " + quote(JSON.stringify(template.permissions)) + "::jsonb").join(" ")} ELSE NULL::jsonb END
$$;
ALTER TABLE iam_assignment_proposals DROP CONSTRAINT iam_assignment_proposals_template_key_check,
 ADD CONSTRAINT iam_assignment_proposals_template_key_check CHECK(iam_assignment_template_permissions(template_key) IS NOT NULL) NOT VALID;
ALTER TABLE iam_assignment_proposals VALIDATE CONSTRAINT iam_assignment_proposals_template_key_check;
ALTER TABLE iam_assignment_snapshots DROP CONSTRAINT iam_assignment_snapshots_template_key_check,
 DROP CONSTRAINT iam_assignment_snapshots_permissions_check,
 ADD CONSTRAINT iam_assignment_snapshots_template_key_check CHECK(iam_assignment_template_permissions(template_key) IS NOT NULL) NOT VALID,
 ADD CONSTRAINT iam_assignment_snapshots_permissions_check CHECK(permissions=iam_assignment_template_permissions(template_key)) NOT VALID;
ALTER TABLE iam_assignment_snapshots VALIDATE CONSTRAINT iam_assignment_snapshots_template_key_check;
ALTER TABLE iam_assignment_snapshots VALIDATE CONSTRAINT iam_assignment_snapshots_permissions_check;
${snapshot.replace(oldPermissions, "iam_assignment_template_permissions(NEW.template_key)")}
`;
await writeTemplateArtifact("backend/internal/modules/iam/assignment_templates_generated.sql", sql);
