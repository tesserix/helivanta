import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(
  await readFile(path.join(root, "contracts/staff-governance.json"), "utf8"),
);
const templateKeys = new Set();
for (const template of source.templates) {
  if (templateKeys.has(template.key))
    throw new Error(`Duplicate governance template: ${template.key}`);
  templateKeys.add(template.key);
}
let go =
  '// Code generated by scripts/generate-staff-governance.mjs; DO NOT EDIT.\npackage iam\n\nimport("time"\n\n"github.com/google/uuid")\n\n';
if (
  !Number.isSafeInteger(source.max_request_bytes) ||
  source.max_request_bytes < 1 ||
  source.time_precision_digits !== 6
)
  throw new Error("Invalid governance bounds");
go += `const governanceInstantQuantumNS=${10 ** (9 - source.time_precision_digits)}\nvar governanceInstantBounds=[2]string{${source.instant_bounds.map((value) => JSON.stringify(value)).join(",")}}\n`;
go += `const governanceInstantPattern=${JSON.stringify(source.instant_pattern)}\n`;
go += `const governanceMaxRequestBytes=${source.max_request_bytes}\n`;
go += `const governanceSubjectMaxUTF16=${source.text_limits.subject}\nconst governanceReasonMaxUTF16=${source.text_limits.reason}\n`;
let ts =
  '// Generated by scripts/generate-staff-governance.mjs.\nimport { z } from "zod";\nimport {staffPostingInstantMicros as instantMicros} from "./staff-postings-contract";\n\n';
ts += `export const governanceTemplates=${JSON.stringify(source.templates)} as const;\n`;
for (const [name, fields] of Object.entries(source.models)) {
  const resolved = fields.map((field) => {
    if (field.enum_ref !== undefined && field.enum_ref !== "templates")
      throw new Error("Unknown governance enum reference");
    let value =
      field.enum_ref === "templates"
        ? { ...field, enum: source.templates.map((item) => item.key) }
        : field;
    if (value.max_ref !== undefined) {
      const max = source.text_limits[value.max_ref];
      if (!Number.isSafeInteger(max) || max < 1 || source.text_length_unit !== "utf16")
        throw new Error("Invalid governance text bound");
      value = { ...value, max, binding: value.binding ? `${value.binding},max=${max}` : undefined };
    }
    return value.enum
      ? {
          ...value,
          binding: [value.binding, `oneof=${value.enum.join(" ")}`].filter(Boolean).join(","),
        }
      : value;
  });
  const emitted = emitModels({ [name]: resolved }, "z.never()");
  go += emitted.go;
  if (name.endsWith("Input"))
    go += `var ${name[0].toLowerCase() + name.slice(1)}Fields=[]string{${fields.map((field) => JSON.stringify(field.name)).join(",")}}\n`;

  // The shared emitter's identifier is file-local; all these models share it.
  let model = emitted.ts.replace(/^const identifier=.*;\n/u, "");
  for (const field of resolved.filter((field) => field.max_ref !== undefined)) {
    model = model.replace(
      `${field.name}:z.string().min(${field.min}).max(${field.max})`,
      `${field.name}:z.string().min(${field.min}).refine(value=>value.length<=${field.max},"Use at most ${field.max} UTF16 units.")`,
    );
  }
  if (name === "GovernanceTemplateDefinition") {
    ts +=
      'const identifier=z.uuid().refine(value=>value!=="00000000-0000-0000-0000-000000000000","Choose a valid record.");\n';
  }
  if (name === "GovernanceGrantInput") {
    model = model.replaceAll(
      "z.string().datetime({ offset: true })",
      `z.string().datetime({ offset: true }).regex(new RegExp(${JSON.stringify(source.instant_pattern)}, "u"), "Use an RFC3339 microsecond instant.")`,
    );
    model = model.replace(
      "export const GovernanceGrantInputContract=",
      "const GovernanceGrantInputShape=",
    );
    model += `export const GovernanceGrantInputContract=GovernanceGrantInputShape.superRefine((value,ctx)=>{
      const definition=governanceTemplates.find(item=>item.key===value.template_key);
      if(!definition || !definition.scope_kinds.some(kind=>kind===value.scope_kind))ctx.addIssue({code:"custom",path:["scope_kind"],message:"Choose the template's exact governance scope."});
      if((value.scope_kind==="tenant")!==(value.scope_id===undefined))ctx.addIssue({code:"custom",path:["scope_id"],message:"Choose the exact employer, or tenant scope without an employer."});
      const lower=instantMicros(${JSON.stringify(source.instant_bounds[0])})!,upper=instantMicros(${JSON.stringify(source.instant_bounds[1])})!;
      const start=instantMicros(value.valid_from),end=instantMicros(value.expires_at);
      for (const key of ["valid_from","expires_at"] as const) {
        const instant=instantMicros(value[key]);
        const fraction=/\\.(\\d+)/u.exec(value[key])?.[1] ?? "";
        if(instant===null || instant<=lower || instant>upper || /[1-9]/u.test(fraction.slice(${source.time_precision_digits})))ctx.addIssue({code:"custom",path:[key],message:"Use a bounded microsecond instant."});
      }
      if(start!==null && end!==null && end<=start)ctx.addIssue({code:"custom",path:["expires_at"],message:"Expiry must be after the start time."});
      if(!value.reason.trim())ctx.addIssue({code:"custom",path:["reason"],message:"Enter a governance reason."});
    });\n`;
  }
  if (name === "GovernanceGrantDecisionInput") {
    model = model.replace(
      "}).strict();",
      '}).strict().refine(value=>value.reason.trim().length>0,{path:["reason"],message:"Enter a governance reason."});',
    );
  }
  ts += model;
}
go += `var governanceTemplates = []GovernanceTemplateDefinition{\n${source.templates.map((item) => `{Key:${JSON.stringify(item.key)},Name:${JSON.stringify(item.name)},ScopeKinds:[]string{${item.scope_kinds.map((v) => JSON.stringify(v)).join(",")}},Permissions:[]string{${item.permissions.map((v) => JSON.stringify(v)).join(",")}}}`).join(",\n")},\n}\n`;
await writeGenerated(
  root,
  "backend/internal/modules/iam/governance_types_generated.go",
  go,
  "packages/api/src/staff-governance-contract.ts",
  ts,
  "Staff governance",
);
