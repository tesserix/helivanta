import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/supplier-access.json"), "utf8"),
);
const models = emitModels(contract.models);
await writeGenerated(
  root,
  "backend/pkg/supplieraccess/types_generated.go",
  `// Code generated by scripts/generate-supplier-access.mjs; DO NOT EDIT.\npackage supplieraccess\nimport("time";"github.com/google/uuid")\n${models.go}\nconst maximumValidityDays=${contract.maximum_validity_days}\nvar templates=map[string]Template{${contract.templates.map((t) => `${JSON.stringify(t.key)}:{Permission:${JSON.stringify(t.permission)},GroupPurposes:[]string{${t.group_purposes.map(JSON.stringify).join(",")}}}`).join(",")}}\n`,
  "packages/api/src/supplier-access-contract.ts",
  `// Code generated by scripts/generate-supplier-access.mjs; DO NOT EDIT.\nimport{z}from"zod";\n${models.ts}`,
  "Effective supplier access",
);

const eventModels = emitModels({
  SupplierGrantScope: contract.models.SupplierGrantScope,
  SupplierGrantInput: contract.models.SupplierGrantInput,
  SupplierGrantExchangeData: contract.models.SupplierGrantExchange,
});
await writeGenerated(
  root,
  "backend/internal/modules/iam/contract/supplier_access_types_generated.go",
  `// Code generated by scripts/generate-supplier-access.mjs; DO NOT EDIT.\npackage contract\nimport("time";"github.com/google/uuid")\n${eventModels.go}`,
  "packages/api/src/supplier-access-contract.ts",
  `// Code generated by scripts/generate-supplier-access.mjs; DO NOT EDIT.\nimport{z}from"zod";\n${models.ts}`,
  "Effective supplier access event",
);
