import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/supplier-orders.json"), "utf8"),
);
const models = emitModels(contract.models);
const productFields = contract.models.SupplierOrderProduct;
const shapes = Object.entries(contract.product_version_fields);
const versionFields = shapes.map(([, field]) => field);
if (
  new Set(versionFields).size !== shapes.length ||
  shapes.length !== productFields.find((field) => field.name === "owner").enum.length
)
  throw new Error("Incomplete product version shapes");
const goName = (field) =>
  field
    .split("_")
    .map((word) => (word === "id" ? "ID" : word[0].toUpperCase() + word.slice(1)))
    .join("");
let productGo =
  "func productValid(p SupplierOrderProduct,owner string)bool{if p.Owner!=owner||p.ProductID==uuid.Nil||p.ProductID.Variant()!=uuid.RFC4122{return false};switch owner{\n";
let productTS = ".superRefine((value,ctx)=>{let valid=false;switch(value.owner){";
for (const [owner, field] of shapes) {
  const definition = productFields.find((value) => value.name === field);
  if (!definition?.optional || !["uuid", "int64"].includes(definition.type))
    throw new Error("Invalid product version shape");
  const other = versionFields.filter((value) => value !== field);
  const checks = [`p.${goName(field)}!=nil`, ...other.map((value) => `p.${goName(value)}==nil`)];
  const tsChecks = [
    `value.${field}!==undefined`,
    ...other.map((value) => `value.${value}===undefined`),
  ];
  if (definition.type === "uuid")
    checks.push(`*p.${goName(field)}!=uuid.Nil`, `p.${goName(field)}.Variant()==uuid.RFC4122`);
  else
    checks.push(`*p.${goName(field)}>=${definition.min}`, `*p.${goName(field)}<=${definition.max}`);
  const productVersion = contract.product_id_versions[owner];
  if (productVersion) {
    checks.push(`p.ProductID.Version()==${productVersion}`);
    tsChecks.push(`value.product_id[14]===${JSON.stringify(String(productVersion))}`);
  }
  productGo += `case ${JSON.stringify(owner)}:return ${checks.join("&&")}\n`;
  productTS += `case ${JSON.stringify(owner)}:valid=${tsChecks.join("&&")};break;`;
}
productGo += "};return false}\n";
productTS +=
  '}if(!valid)ctx.addIssue({code:"custom",message:"Use the selected stock owner’s exact product/version reference."});})';
models.ts = models.ts.replace(
  "}).strict();\nexport type SupplierOrderProduct",
  "}).strict()" + productTS + ";\nexport type SupplierOrderProduct",
);

await writeGenerated(
  root,
  "backend/pkg/supplierorder/types_generated.go",
  '// Code generated by scripts/generate-supplier-orders.mjs; DO NOT EDIT.\npackage supplierorder\nimport("time";"github.com/google/uuid";"github.com/tesserix/helivanta/pkg/suppliertrade")\n' +
    models.go.replaceAll("SupplierTradeTerms", "suppliertrade.Terms") +
    productGo +
    `\nconst maximumLines=${contract.maximum_lines}\n`,
  "packages/api/src/supplier-orders-contract.ts",
  '// Code generated by scripts/generate-supplier-orders.mjs; DO NOT EDIT.\nimport{z}from"zod";\nimport{SupplierTradeTermsContract}from"./supplier-trade-contract";\n' +
    models.ts,
  "Supplier orders",
);

const wireModels = {};
for (const name of ["SupplierOrderProduct", "SupplierOrderLine", "SupplierOrderInput"])
  wireModels[name] = contract.models[name];
wireModels.OrderExchangeData = contract.models.SupplierOrderExchange;
const wire = emitModels(wireModels);
const wirePath = path.join(
  root,
  "backend/internal/modules/supply/contract/order_types_generated.go",
);
const wireBody = execFileSync("gofmt", [], {
  input:
    '// Code generated by scripts/generate-supplier-orders.mjs; DO NOT EDIT.\npackage contract\nimport("time";"github.com/google/uuid")\n' +
    wire.go,
  encoding: "utf8",
});
if (process.argv.includes("--check")) {
  if ((await readFile(wirePath, "utf8")) !== wireBody)
    throw new Error("Published supplier order contract is stale");
} else await writeFile(wirePath, wireBody);
