import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/supplier-trade.json"), "utf8"),
);
const policy = JSON.parse(await readFile(path.join(root, "contracts/trading-policy.json"), "utf8"));
for (const fields of Object.values(contract.models))
  for (const field of fields) {
    if (field.policy_field) {
      const source = policy.models.Submission.find((f) => f.name === field.policy_field);
      if (!source?.enum) throw new Error("Missing policy field");
      field.enum = source.enum;
    }
  }
const models = emitModels(contract.models);
const category = contract.models.SupplierTradeTerms.find((f) => f.name === "category").enum;
await writeGenerated(
  root,
  "backend/pkg/suppliertrade/types_generated.go",
  `// Code generated by scripts/generate-supplier-trade.mjs; DO NOT EDIT.\npackage suppliertrade\nimport("time";"github.com/google/uuid")\n${models.go}\nconst maximumValidityDays=${contract.maximum_validity_days}\nvar categories=[]string{${category.map(JSON.stringify).join(",")}}\n`,
  "packages/api/src/supplier-trade-contract.ts",
  `// Code generated by scripts/generate-supplier-trade.mjs; DO NOT EDIT.\nimport{z}from"zod";\n${models.ts}`,
  "Bilateral supplier trade",
);
const sq = (v) => `'${String(v).replaceAll("'", "''")}'`;
const scope = contract.models.PharmacyTradingScopeInput;
const scopeCategory = scope.find((f) => f.name === "category").enum;
const jurisdiction = scope.find((f) => f.name === "jurisdiction").enum;
const shape = `CREATE FUNCTION pharmacy_trading_scope_input_valid(v jsonb)RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
 SELECT COALESCE(CASE WHEN jsonb_typeof(v)='object' THEN
 v ?& ARRAY[${scope.map((f) => sq(f.name)).join(",")}] AND(SELECT count(*)FROM jsonb_object_keys(v))=${scope.length}
 AND jsonb_typeof(v->'licence_id')='string'AND v->>'licence_id'~'^[a-f0-9]{8}-[a-f0-9]{4}-7[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$'
 AND v->>'jurisdiction' IN(${jurisdiction.map(sq).join(",")})AND v->>'category' IN(${scopeCategory.map(sq).join(",")})
 AND jsonb_typeof(v->'reason')='string'AND length(btrim(v->>'reason'))BETWEEN 1 AND 500 AND v->>'reason'!~'[[:cntrl:]]'
 AND v->'attest_premise_and_licence_scope'='true'::jsonb ELSE false END,false)
$$;`;
await writeGenerated(
  root,
  "backend/internal/modules/pharmacy/trading_scope_contract_generated.go",
  `// Code generated by scripts/generate-supplier-trade.mjs; DO NOT EDIT.\npackage pharmacy\nconst tradingScopeContractSchema=\x60${shape}\x60\n`,
  "packages/api/src/supplier-trade-contract.ts",
  `// Code generated by scripts/generate-supplier-trade.mjs; DO NOT EDIT.\nimport{z}from"zod";\n${models.ts}`,
  "Pharmacy trading scope shape",
);
const exchangeModels = emitModels({
  SupplierTradeEndpoint: contract.models.SupplierTradeEndpoint,
  SupplierTradeTerms: contract.models.SupplierTradeTerms,
  RelationshipExchangeData: contract.models.SupplierRelationshipExchange,
});
await writeGenerated(
  root,
  "backend/internal/modules/supply/contract/trade_types_generated.go",
  `// Code generated by scripts/generate-supplier-trade.mjs; DO NOT EDIT.\npackage contract\nimport("time";"github.com/google/uuid")\n${exchangeModels.go}`,
  "packages/api/src/supplier-trade-contract.ts",
  `// Code generated by scripts/generate-supplier-trade.mjs; DO NOT EDIT.\nimport{z}from"zod";\n${models.ts}`,
  "Directed supplier relationship contract",
);
