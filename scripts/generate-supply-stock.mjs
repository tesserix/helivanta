import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(await readFile(path.join(root, "contracts/supply-stock.json"), "utf8"));
const models = emitModels(contract.models);
for (const fields of Object.values(contract.models)) {
  for (const field of fields) {
    if (Object.hasOwn(field, "literal"))
      models.ts = models.ts.replace(
        `${field.name}:z.boolean()`,
        `${field.name}:z.literal(${JSON.stringify(field.literal)})`,
      );
  }
}
await writeGenerated(
  root,
  "backend/internal/modules/supply/stock_types_generated.go",
  '// Code generated by scripts/generate-supply-stock.mjs; DO NOT EDIT.\npackage supply\nimport("time";"github.com/google/uuid";"github.com/tesserix/helivanta/pkg/stockproduct")\n' +
    models.go.replaceAll("StockProductReference", "stockproduct.Reference"),
  "packages/api/src/supply-stock-contract.ts",
  '// Generated by scripts/generate-supply-stock.mjs.\nimport {z} from "zod";\nimport {ReferenceContract as StockProductReferenceContract} from "./stock-product-contract";\n' +
    models.ts,
  "Supply stock",
);
