import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/trading-policy.json"), "utf8"),
);
const countryMetadata = JSON.parse(
  await readFile(path.join(root, "contracts/country-profiles.json"), "utf8"),
);
for (const field of contract.models.Submission) {
  if (field.country_profile) field.enum = countryMetadata.countries.map((country) => country.code);
  if (field.country_currency)
    field.enum = [...new Set(countryMetadata.countries.map((country) => country.currency))];
}
const models = emitModels(contract.models);
const domains = contract.models.Requirement.find((field) => field.name === "domain").enum;
const categories = contract.models.Submission.find((field) => field.name === "category").enum;
const operations = contract.models.Submission.find((field) => field.name === "operation").enum;
const revision = contract.models.Submission.find((field) => field.name === "expected_revision").max;
const goRules = `const maxPolicyRevision=${revision}\nvar requirementDomains=[]string{${domains.map(JSON.stringify).join(",")}}\nvar policyCategories=[]string{${categories.map(JSON.stringify).join(",")}}\nvar policyOperations=[]string{${operations.map(JSON.stringify).join(",")}}\n`;
await writeGenerated(
  root,
  "backend/pkg/tradingpolicy/input_types.go",
  '// Code generated by scripts/generate-trading-policy.mjs; DO NOT EDIT.\npackage tradingpolicy\n\nimport "time"\n\n' +
    goRules +
    models.go,
  "packages/api/src/trading-policy-contract.ts",
  '// Generated by scripts/generate-trading-policy.mjs.\nimport { z } from "zod";\n\n' + models.ts,
  "trading policy",
);
