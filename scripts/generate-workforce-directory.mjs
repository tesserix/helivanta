import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/workforce-directory.json"), "utf8"),
);
const models = emitModels(
  Object.fromEntries(
    Object.entries(contract.models).map(([name, fields]) => [
      name,
      fields.map((field) =>
        field.projection_version
          ? {
              ...field,
              enum: [contract.projection.version],
              binding: `omitempty,oneof=${contract.projection.version}`,
            }
          : field,
      ),
    ]),
  ),
);
await writeGenerated(
  root,
  "backend/internal/modules/workforce/directory_types.go",
  "// Code generated by scripts/generate-workforce-directory.mjs; DO NOT EDIT.\npackage workforce\n\n" +
    `const staffDirectoryContextQuery=${JSON.stringify(contract.projection.query)}\nconst staffDirectoryContextVersion=${JSON.stringify(contract.projection.version)}\n\n` +
    models.go,
  "packages/api/src/staff-directory-contract.ts",
  '// Generated by scripts/generate-workforce-directory.mjs.\nimport { z } from "zod";\n\n' +
    `export const STAFF_DIRECTORY_CONTEXT=${JSON.stringify(contract.projection)} as const;\n` +
    models.ts,
  "staff directory editing",
);
