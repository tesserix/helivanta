import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/workforce-documents.json"), "utf8"),
);
const kinds = Object.keys(contract.records);
const categories = [...new Set(Object.values(contract.records).flat())];
const pascal = (name) =>
  name
    .split("_")
    .map((part) =>
      part === "id" ? "ID" : part === "sha256" ? "SHA256" : part[0].toUpperCase() + part.slice(1),
    )
    .join("");
const enumerations = {
  record_kind: kinds,
  category: categories,
  content_type: contract.content_types,
  status: contract.statuses,
  failure_code: contract.failure_codes,
};
const goType = (format) => {
  const base = format.replace("?", "");
  const value =
    {
      uuid: "uuid.UUID",
      positive: "int64",
      size: "int64",
      timestamp: "time.Time",
      categories: "[]string",
    }[base] ?? "string";
  return format.endsWith("?") ? "*" + value : value;
};
const binding = (format) => {
  if (enumerations[format]) return "required,oneof=" + enumerations[format].join(" ");
  return {
    uuid: "required",
    filename: `required,max=${contract.max_filename}`,
    size: `required,min=1,max=${contract.max_bytes}`,
    sha256: "required,len=64",
  }[format];
};
let go =
  '// Code generated by scripts/generate-workforce-documents.mjs; DO NOT EDIT.\npackage workforce\nimport("time";"github.com/google/uuid")\n';
go += `var documentCategoryBindings = map[string][]string{${Object.entries(contract.records)
  .map(([kind, values]) => `${JSON.stringify(kind)}:{${values.map(JSON.stringify).join(",")}},`)
  .join("")}}\n`;
for (const [group, type] of [
  ["input", "documentInput"],
  ["document", "document"],
  ["record_choice", "documentRecordChoice"],
]) {
  go += `type ${type} struct {\n`;
  for (const [name, format, visibility] of contract[group]) {
    const rule = group === "input" ? binding(format) : undefined;
    go += `${pascal(name)} ${goType(format)} \`json:"${visibility === "hidden" ? "-" : name}"${rule ? ` binding:"${rule}"` : ""}\`\n`;
  }
  go += "}\n";
}
let ts = '// Generated by scripts/generate-workforce-documents.mjs.\nimport { z } from "zod";\n';
ts += `export const MAX_DOCUMENT_BYTES = ${contract.max_bytes};\nexport const DOCUMENT_CATEGORIES = ${JSON.stringify(contract.records)} as const;\n`;
ts +=
  'const identifier=z.string().guid().refine(value=>value!=="00000000-0000-0000-0000-000000000000","Choose a valid record.");\n';
ts += `const filename=z.string().trim().refine(value=>[...value].length>=1 && [...value].length<=${contract.max_filename} && value!=="." && value!==".." && !/[\\\\/\\p{Cc}]/u.test(value),"Choose a file with a safe name (up to ${contract.max_filename} characters).");\n`;
const schema = (format) => {
  const base = format.replace("?", "");
  const value = enumerations[base]
    ? `z.enum(${JSON.stringify(enumerations[base])})`
    : {
        uuid: "identifier",
        filename: "filename",
        size: "z.number().int().min(1).max(MAX_DOCUMENT_BYTES)",
        positive: "z.number().int().safe().min(1)",
        timestamp: "z.string().datetime({offset:true})",
        sha256: "z.string().regex(/^[a-f0-9]{64}$/)",
        label: "z.string().min(1).max(350)",
        categories: `z.array(z.enum(${JSON.stringify(categories)})).min(1).max(2)`,
        string: "z.string()",
      }[base];
  if (!value) throw new Error("Unknown document format: " + format);
  return value + (format.endsWith("?") ? ".nullable()" : "");
};
for (const [group, name, type] of [
  ["input", "documentInputSchema", "DocumentInput"],
  ["document", "staffDocumentSchema", "StaffDocument"],
  ["record_choice", "documentRecordChoiceSchema", "DocumentRecordChoice"],
]) {
  ts += `export const ${name}=z.object({\n`;
  for (const [key, format, visibility] of contract[group])
    if (visibility !== "hidden") ts += `${key}:${schema(format)},\n`;
  ts += "})" + (group === "input" ? ".strict()" : "");
  if (group === "input")
    ts +=
      '.superRefine((value,ctx)=>{if(!(DOCUMENT_CATEGORIES[value.record_kind] as readonly string[]).includes(value.category))ctx.addIssue({code:"custom",path:["category"],message:"Choose evidence for the selected record."})})';
  if (group === "record_choice")
    ts +=
      '.superRefine((value,ctx)=>{if(new Set(value.categories).size!==value.categories.length || value.categories.some(category=>!(DOCUMENT_CATEGORIES[value.record_kind] as readonly string[]).includes(category)))ctx.addIssue({code:"custom",path:["categories"],message:"Record purposes do not match."})})';
  ts += `;\nexport type ${type}=z.infer<typeof ${name}>;\n`;
}
ts +=
  "export const documentRecordsSchema=z.object({records:z.array(documentRecordChoiceSchema).max(41),uploads_available:z.boolean()});\nexport type DocumentRecords=z.infer<typeof documentRecordsSchema>;\n";
const outputs = {
  "backend/internal/modules/workforce/documents_types.go": execFileSync("gofmt", [], {
    input: go,
    encoding: "utf8",
  }),
  "packages/api/src/documents-fields.ts": execFileSync(
    "pnpm",
    ["exec", "prettier", "--stdin-filepath", "packages/api/src/documents-fields.ts"],
    { cwd: root, input: ts, encoding: "utf8" },
  ),
};
for (const [file, content] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path.join(root, file), "utf8")) !== content)
      throw new Error("Generated document contract is stale: " + file);
  } else await writeFile(path.join(root, file), content);
}
