import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/workforce-employment-periods.json"), "utf8"),
);
const models = emitModels(contract.models);
const termsValidation = `
const validTerms = (value: {duration: string; starts_at: string; ends_at?: string; engagement_kind: string; contracting_party: string; sponsor_id: string}, ctx: z.RefinementCtx) => {
 if(value.duration === "fixed" && (!value.ends_at || Date.parse(value.ends_at) <= Date.parse(value.starts_at))) ctx.addIssue({code:"custom",path:["ends_at"],message:"Fixed terms require an end after the start."});
 if(value.duration === "ongoing" && value.ends_at !== undefined) ctx.addIssue({code:"custom",path:["ends_at"],message:"Ongoing terms cannot have an end."});
 if(["contractor","agency_worker"].includes(value.engagement_kind)) {
  if(!value.contracting_party.trim()) ctx.addIssue({code:"custom",path:["contracting_party"],message:"Name the contracting party."});
  if(!value.sponsor_id) ctx.addIssue({code:"custom",path:["sponsor_id"],message:"Choose an accountable hospital sponsor."});
 }
 if(value.sponsor_id && !z.string().uuid().safeParse(value.sponsor_id).success) ctx.addIssue({code:"custom",path:["sponsor_id"],message:"Choose a valid sponsor."});
};
`;
const refinedTs = models.ts.replace(
  /(export const EmploymentPeriod(?:DraftInput|Draft)Contract=z\.object\(\{[\s\S]*?\}\)\.strict\(\));/g,
  "$1.superRefine(validTerms);",
);
await writeGenerated(
  root,
  "backend/internal/modules/workforce/employment_period_types.go",
  '// Code generated by scripts/generate-workforce-employment-periods.mjs; DO NOT EDIT.\npackage workforce\nimport("time";"github.com/google/uuid")\n' +
    models.go,
  "packages/api/src/employment-periods-contract.ts",
  '// Generated by scripts/generate-workforce-employment-periods.mjs.\nimport {z} from "zod";\n' +
    termsValidation +
    refinedTs,
  "staff employment period drafts",
);
