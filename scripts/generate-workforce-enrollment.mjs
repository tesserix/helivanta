import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const {
  profile_masters: profileMasters,
  profile_masters_projection: profileMastersProjection,
  qualification_masters_projection: qualificationMastersProjection,
  contact_masters_projection: contactMastersProjection,
  ...groups
} = JSON.parse(await readFile(path.join(root, "contracts/workforce-enrollment.json"), "utf8"));
if (
  !profileMastersProjection ||
  typeof profileMastersProjection !== "object" ||
  Array.isArray(profileMastersProjection) ||
  Object.keys(profileMastersProjection).sort().join(",") !== "query,response_field,version" ||
  !/^[a-z][a-z_]*$/.test(profileMastersProjection.query) ||
  !/^[a-z][a-z_]*$/.test(profileMastersProjection.response_field) ||
  !/^v[1-9][0-9]*$/.test(profileMastersProjection.version)
)
  throw new Error("Invalid enrollment profile master projection");
const childProjections = [
  ["Qualification", "qualifications", qualificationMastersProjection],
  ["Contact", "emergency_contacts", contactMastersProjection],
];
for (const [name, , projection] of childProjections) {
  const query = `${name.toLowerCase()}_masters`;
  if (
    !projection ||
    Object.keys(projection).sort().join(",") !== "query,response_field,version" ||
    projection.query !== query ||
    projection.version !== "v1" ||
    projection.response_field !== `${query}_version`
  )
    throw new Error(`Invalid enrollment ${name.toLowerCase()} master projection`);
}
const relationshipLimit = groups.emergency_contacts.find(
  ([field]) => field === "relationship",
)?.[1];
if (!Number.isInteger(relationshipLimit) || relationshipLimit <= 0)
  throw new Error("Invalid emergency contact relationship limit");
const referenceFields = groups.profile.filter(([name]) => name.endsWith("_revision_id"));
if (
  !Array.isArray(profileMasters) ||
  profileMasters.length !== referenceFields.length ||
  new Set(profileMasters.map(([kind]) => kind)).size !== profileMasters.length ||
  new Set(profileMasters.map(([, field]) => field)).size !== profileMasters.length ||
  profileMasters.some(
    ([kind, field, rejectNull, selectionOnly]) =>
      typeof kind !== "string" ||
      !/^[a-z][a-z_]*$/.test(kind) ||
      !groups.profile.some(([name, type]) => name === field && typeof type === "number") ||
      !referenceFields.some(([name, type]) => name === `${field}_revision_id` && type === "uuid") ||
      typeof rejectNull !== "boolean" ||
      typeof selectionOnly !== "boolean",
  )
)
  throw new Error("Invalid enrollment profile master mapping");

const names = {
  profile: "Profile",
  addresses: "Address",
  emergency_contacts: "Contact",
  credentials: "Credential",
  qualifications: "Qualification",
  experiences: "Experience",
};
const pascal = (s) =>
  s
    .split("_")
    .map((part) => (part === "id" ? "ID" : part[0].toUpperCase() + part.slice(1)))
    .join("");
const enums = {
  gender: ["", "female", "male", "other", "prefer_not_to_say"],
  blood_group: ["", "A+", "A-", "B+", "B-", "AB+", "AB-", "O+", "O-"],
  engagement_type: ["employee", "consultant", "contractor", "locum", "trainee", "volunteer"],
  use: ["current", "permanent"],
};
const required = new Set([
  "addresses.line1",
  "addresses.country",
  "emergency_contacts.name",
  "emergency_contacts.relationship",
  "emergency_contacts.phone",
  "credentials.type",
  "credentials.number",
  "credentials.issuer",
  "qualifications.qualification",
  "qualifications.institution",
  "experiences.employer",
  "experiences.role",
  "experiences.start_date",
]);
let go =
  "// Code generated by scripts/generate-workforce-enrollment.mjs; DO NOT EDIT.\npackage workforce\n\n";
let ts = '// Generated by scripts/generate-workforce-enrollment.mjs.\nimport { z } from "zod";\n\n';
ts += `const dateOnly = z.string().refine(value => value === "" || (/^\\d{4}-\\d{2}-\\d{2}$/.test(value) && !Number.isNaN(Date.parse(value)) && new Date(value).toISOString().slice(0,10) === value && value >= "1900-01-01" && value <= "2200-12-31"), "Enter a valid date.");
export const internationalPhone = z.string().regex(/^(\\+[1-9][0-9]{6,14})?$/, "Use an international number, for example +61400000001.");
const country = z.string().regex(/^([A-Z]{2})?$/, "Use a two-letter country code, such as AU or IN.");
const email = z.union([z.literal(""), z.string().max(254).email("Enter a valid email address.")]);
const identifier = z.string().guid().refine(value => value !== "00000000-0000-0000-0000-000000000000", "Choose a valid record.");\n`;
for (const [group, fields] of Object.entries(groups)) {
  go += `type enrollment${names[group]} struct {\n`;
  ts += `export const enrollment${names[group]}Schema = z.object({\n`;
  if (group !== "profile") {
    go += 'ID string `json:"id" binding:"required,uuid"`\n';
    ts += "id: identifier,\n";
  }
  for (const [name, kind, optional] of fields) {
    if (optional !== undefined && typeof optional !== "boolean")
      throw new Error(`Invalid optional enrollment field: ${group}.${name}`);
    const numeric = kind === "int" || kind === "year";
    const rule =
      {
        email: "omitempty,max=254,email",
        phone: "omitempty,max=25",
        date: "omitempty,max=10",
        uuid: "omitempty,uuid",
        int: "gte=1,lte=5",
        year: "gte=0,lte=2200",
      }[kind] ?? `max=${kind}`;
    go += `${pascal(name)} ${numeric ? "int" : "string"} \`json:"${name}" binding:"${rule}"\`\n`;
    let schema = enums[name]
      ? `z.enum(${JSON.stringify(enums[name])})`
      : ({
          email: "email",
          phone: "internationalPhone",
          date: "dateOnly",
          uuid: 'z.union([z.literal(""), identifier])',
          int: "z.number().int().min(1).max(5)",
          year: 'z.number().int().refine(value => value === 0 || (value >= 1900 && value <= new Date().getUTCFullYear()), "Enter a valid completion year.")',
        }[kind] ?? (name === "country" ? "country" : `z.string().trim().max(${kind})`));
    if (name === "country") schema = "country";
    if (required.has(`${group}.${name}`))
      schema += '.refine(value => value !== "", "Complete this field.")';
    if (optional) schema += ".optional()";
    ts += `${name}: ${schema},\n`;
  }
  go += "}\n\n";
  ts += "}).strict()";
  if (group === "profile") {
    const checks = profileMasters
      .filter((entry) => entry[3])
      .map(
        ([, field]) =>
          `if (value.${field} && !value.${field}_revision_id) ctx.addIssue({code: "custom", path: ["${field}_revision_id"], message: "Choose an HR setup record."});`,
      );
    if (checks.length) ts += `.superRefine((value, ctx) => {${checks.join("\n")}})`;
  }
  ts += `;\nexport type Enrollment${names[group]} = z.infer<typeof enrollment${names[group]}Schema>;\n`;
  const defaults = Object.fromEntries(
    fields.map(([name, kind]) => [
      name,
      kind === "int"
        ? 1
        : kind === "year"
          ? 0
          : name === "engagement_type"
            ? "employee"
            : name === "use"
              ? "current"
              : "",
    ]),
  );
  ts += `export const EMPTY_${group.toUpperCase()} = ${JSON.stringify(defaults)} as const;\n\n`;
}
go += `type enrollmentMasterReference struct {
 kind, field string
 id, name *string
 previous string
 rejectNull, selectionOnly bool
}
func enrollmentMasterReferences(in *enrollmentProfile, previous enrollmentProfile) []enrollmentMasterReference {
 return []enrollmentMasterReference{
${profileMasters
  .map(
    ([kind, field, rejectNull, selectionOnly]) =>
      `{${JSON.stringify(kind)},${JSON.stringify(field)},&in.${pascal(field + "_revision_id")},&in.${pascal(field)},previous.${pascal(field + "_revision_id")},${rejectNull},${selectionOnly}},`,
  )
  .join("\n")}
 }
}
`;
ts += `export const ENROLLMENT_PROFILE_MASTERS = ${JSON.stringify(Object.fromEntries(profileMasters.map(([kind, field, , selectionOnly]) => [kind, { field, selectionOnly }])))} as const;\n`;
go += `const enrollmentProfileMastersQuery = ${JSON.stringify(profileMastersProjection.query)}
const enrollmentProfileMastersVersion = ${JSON.stringify(profileMastersProjection.version)}
type enrollmentProfileMastersProjection struct {
Version string \`json:"${profileMastersProjection.response_field}"\`
}
func legacyEnrollmentProfile(in enrollmentProfile) map[string]any {
return map[string]any{
${groups.profile
  .filter(([, , optional]) => !optional)
  .map(([field]) => `${JSON.stringify(field)}: in.${pascal(field)},`)
  .join("\n")}
}
}
`;
ts += `export const ENROLLMENT_PROFILE_MASTERS_PROJECTION = ${JSON.stringify(profileMastersProjection)} as const;\n`;
ts += `export type EnrollmentProfileMastersProjection = { ${JSON.stringify(profileMastersProjection.response_field)}: typeof ENROLLMENT_PROFILE_MASTERS_PROJECTION.version };\n`;
for (const [name, , projection] of childProjections) {
  go += `const enrollment${name}MastersQuery = ${JSON.stringify(projection.query)}
const enrollment${name}MastersVersion = ${JSON.stringify(projection.version)}\n`;
  ts += `export const ENROLLMENT_${name.toUpperCase()}_MASTERS_PROJECTION = ${JSON.stringify(projection)} as const;\n`;
  ts += `export type Enrollment${name}MastersProjection = { ${JSON.stringify(projection.response_field)}: typeof ENROLLMENT_${name.toUpperCase()}_MASTERS_PROJECTION.version };\n`;
}
go += `const enrollmentContactRelationshipMaxLength = ${relationshipLimit}\n`;
ts += `export const ENROLLMENT_CONTACT_RELATIONSHIP_MAX_LENGTH = ${relationshipLimit};\n`;
go += `func enrollmentResponse(in enrollment, profileMasters, qualificationMasters, contactMasters bool) map[string]any {
 result := map[string]any{"staff":in.Staff,"version":in.Version,
${Object.keys(groups)
  .map(
    (group) =>
      `${JSON.stringify(group)}:in.${group === "emergency_contacts" ? "EmergencyContacts" : pascal(group)},`,
  )
  .join("\n")}
 }
 if profileMasters { result[${JSON.stringify(profileMastersProjection.response_field)}] = enrollmentProfileMastersVersion } else { result["profile"] = legacyEnrollmentProfile(in.Profile) }
`;
for (const [name, group, projection] of childProjections) {
  const field = group === "emergency_contacts" ? "EmergencyContacts" : pascal(group);
  go += `if ${name.toLowerCase()}Masters { result[${JSON.stringify(projection.response_field)}] = enrollment${name}MastersVersion } else {
 rows := make([]map[string]any,0,len(in.${field}))
 for _, row := range in.${field} { rows = append(rows,map[string]any{"id":row.ID,
${groups[group]
  .filter(([, , optional]) => !optional)
  .map(([field]) => `${JSON.stringify(field)}:row.${pascal(field)},`)
  .join("\n")}
 }) }
 result[${JSON.stringify(group)}] = rows
 }
`;
}
go += "return result\n}\n";

const outputs = {
  "backend/internal/modules/workforce/enrollment_types.go": execFileSync("gofmt", [], {
    input: go,
    encoding: "utf8",
  }),
  "packages/api/src/enrollment-fields.ts": execFileSync(
    "pnpm",
    ["exec", "prettier", "--stdin-filepath", "packages/api/src/enrollment-fields.ts"],
    { cwd: root, input: ts, encoding: "utf8" },
  ),
};
for (const [file, content] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path.join(root, file), "utf8")) !== content)
      throw new Error(`Generated enrollment contract is stale: ${file}`);
  } else await writeFile(path.join(root, file), content);
}
