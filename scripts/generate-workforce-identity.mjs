import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/workforce-identity-checks.json"), "utf8"),
);
const models = emitModels(contract.models);
const imports = ['"github.com/google/uuid"', '"github.com/tesserix/helivanta/pkg/authz"'];
if (models.go.includes("time.Time")) imports.push('"time"');
const projectionEntries = [
  ["IdentitySourceProjectionQuery", contract.source_projection.query_key],
  ["IdentitySourceDraftProjection", contract.source_projection.draft_value],
];
const projectionGo = projectionEntries
  .map(([name, value]) => `const ${name}=${JSON.stringify(value)}\n`)
  .join("");
const projectionTs = projectionEntries
  .map(([name, value]) => `export const ${name}=${JSON.stringify(value)};\n`)
  .join("");
const permissions = `const PermIdentityChecksManage authz.Permission=${JSON.stringify(contract.permissions.manage)}\nconst PermIdentityChecksReview authz.Permission=${JSON.stringify(contract.permissions.review)}\n`;
await writeGenerated(
  root,
  "backend/internal/modules/workforce/identity_types.go",
  "// Code generated by scripts/generate-workforce-identity.mjs; DO NOT EDIT.\npackage workforce\nimport(" +
    imports.join(";") +
    ")\n" +
    permissions +
    projectionGo +
    models.go,
  "packages/api/src/identity-checks-contract.ts",
  '// Generated by scripts/generate-workforce-identity.mjs.\nimport {z} from "zod";\n' +
    projectionTs +
    models.ts,
  "staff identity checks",
);
