import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { emitModels, writeGenerated } from "./lib/contract-codegen.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/workforce-independent-identity.json"), "utf8"),
);
const login = JSON.parse(
  await readFile(path.join(root, "contracts/workforce-login-links.json"), "utf8"),
);
for (const projection of contract.model_projections) {
  contract.models[projection.model] = [
    ...(projection.prepend ?? []),
    ...login.models[projection.source].map((field) => ({
      ...field,
      ...(projection.overrides?.[field.name] ?? {}),
    })),
  ];
}
const order = [
  "IndependentIdentityScope",
  "IndependentLinkInput",
  "IndependentLinkDecisionInput",
  "IndependentLinkData",
  "IndependentLinkView",
  "IndependentLinkProposal",
  "IndependentLinkCommand",
];
const models = emitModels(
  Object.fromEntries(order.map((name) => [name, contract.models[name]])),
  "loginLinkStatusSchema",
);
await writeGenerated(
  root,
  "backend/internal/modules/workforce/independent_identity_types_generated.go",
  '// Code generated by scripts/generate-workforce-independent-identity.mjs; DO NOT EDIT.\npackage workforce\nimport("time";"github.com/google/uuid")\n' +
    models.go,
  "packages/api/src/workforce-independent-identity-contract.ts",
  '// Generated by scripts/generate-workforce-independent-identity.mjs.\nimport {z} from "zod";\nimport {loginLinkStatusSchema} from "./login-link-contract";\n' +
    models.ts,
  "Independent Staff identity",
);
