import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(
  await readFile(path.join(root, "contracts/workforce-roster-config.json"), "utf8"),
);
const pascal = (value) =>
  value
    .split("_")
    .map((word) =>
      word === "id" ? "ID" : word === "ids" ? "IDs" : word[0].toUpperCase() + word.slice(1),
    )
    .join("");
const kinds = Object.keys(contract.kinds);
let go =
  '// Code generated by scripts/generate-workforce-roster-config.mjs; DO NOT EDIT.\npackage workforce\n\nimport("time";"github.com/google/uuid")\n\n';
go += `var rosterConfigKinds=[]string{${kinds.map((k) => JSON.stringify(k)).join(",")}}\n`;
let ts =
  '// Generated by scripts/generate-workforce-roster-config.mjs.\nimport { z } from "zod";\n\n';
ts += `export const ROSTER_CONFIG_KINDS=${JSON.stringify(contract.kinds)} as const;\nexport const rosterConfigKindSchema=z.enum(${JSON.stringify(kinds)});\n`;
ts +=
  'const identifier=z.string().uuid("Choose a valid record.").refine(value=>value!=="00000000-0000-0000-0000-000000000000","Choose a valid record.");\n';
for (const [name, fields] of Object.entries(contract.models)) {
  go += `type ${name} struct{\n`;
  ts += `export const ${name}Contract=z.object({\n`;
  for (const f of fields) {
    const array = f.type.startsWith("[]");
    const base = array ? f.type.slice(2) : f.type;
    let goType = { uuid: "uuid.UUID", time: "time.Time", kind: "string" }[base] ?? base;
    if (array) goType = "[]" + goType;
    else if (f.pointer || f.optional) goType = "*" + goType;
    const tags = [`json:"${f.name}${f.optional ? ",omitempty" : ""}"`];
    if (f.binding) tags.push(`binding:"${f.binding}"`);
    if (f.orm_ignore) tags.push('gorm:"-"');
    go += `${pascal(f.name)} ${goType} \`${tags.join(" ")}\`\n`;
    let schema =
      {
        uuid: "identifier",
        time: "z.string().datetime({ offset: true })",
        kind: "rosterConfigKindSchema",
        int: "z.number().int()",
        int64: "z.number().int()",
        bool: "z.boolean()",
        string: "z.string()",
      }[base] ?? `${base}Contract`;
    if (array) {
      schema = `z.array(${schema})`;
      if (f.max !== undefined) schema += `.max(${f.max})`;
    } else {
      if (base === "string" && ["code", "name", "text"].includes(f.format)) schema += ".trim()";
      if (f.format === "code")
        schema +=
          '.toUpperCase().regex(/^[A-Z0-9_-]{1,40}$/, "Use letters, numbers, underscores or hyphens.")';
      if (f.min !== undefined)
        schema += `.min(${f.min}${f.format === "name" ? ', "Enter a name."' : ""})`;
      if (f.max !== undefined) schema += `.max(${f.max})`;
      if (f.format === "date")
        schema +=
          '.date("Use a valid date.").refine(value=>value>="0001-01-01","Use a valid date.")';
      if (base === "string")
        schema += '.refine(value=>!value.includes("\\0"),"Remove invalid characters.")';
    }
    if (f.optional) schema += ".optional()";
    ts += `${f.name}:${schema},\n`;
  }
  go += "}\n\n";
  ts += `}).strict();\nexport type ${name[0].toUpperCase() + name.slice(1)}=z.infer<typeof ${name}Contract>;\n\n`;
}
const outputs = {
  "backend/internal/modules/workforce/roster_config_types.go": execFileSync("gofmt", [], {
    input: go,
    encoding: "utf8",
  }),
  "packages/api/src/roster-config-contract.ts": execFileSync(
    "pnpm",
    ["exec", "prettier", "--stdin-filepath", "packages/api/src/roster-config-contract.ts"],
    { cwd: root, input: ts, encoding: "utf8" },
  ),
};
for (const [file, content] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if ((await readFile(path.join(root, file), "utf8")) !== content)
      throw new Error(`Generated roster contract is stale: ${file}`);
  } else await writeFile(path.join(root, file), content);
}
