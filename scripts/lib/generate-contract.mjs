import { readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

export async function generateContract(moduleName) {
  const contract = JSON.parse(
    await readFile(path.join(root, `contracts/${moduleName}.json`), "utf8"),
  );
  const { models } = contract;
  const countryMetadata = JSON.parse(
    await readFile(path.join(root, "contracts/country-profiles.json"), "utf8"),
  );
  const names = Object.fromEntries(models.map((model) => [model.name, model.schema]));
  const pascal = (name) =>
    name
      .split("_")
      .map((part) =>
        part === "sku"
          ? "SKU"
          : part === "id"
            ? "ID"
            : part === "mrp"
              ? "MRP"
              : part[0].toUpperCase() + part.slice(1),
      )
      .join("");
  let go = `// Code generated by scripts/generate-${moduleName}-contract.mjs; DO NOT EDIT.\npackage ${moduleName}\n\n${contract.go_patterns ? 'import ("github.com/google/uuid"; "regexp")' : 'import "github.com/google/uuid"'}\n\n`;
  let ts = `// Generated by scripts/generate-${moduleName}-contract.mjs.\nimport { z } from "zod";\n\nconst identifier=z.string().uuid().regex(/^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i,"Choose a valid record.");\n`;
  for (const model of models) {
    if (model.scope_policy)
      ts += `export const ${model.scope_export}=${JSON.stringify(model.scope_policy)} as const;\n`;
    go += `type ${model.name} struct{\n`;
    ts += `export const ${model.schema}=${model.embed ? names[model.embed] + ".extend" : "z.object"}({\n`;
    for (const originalField of model.fields) {
      const field = originalField.country_profile
        ? { ...originalField, enum: countryMetadata.countries.map((p) => p.code) }
        : originalField.country_currency
          ? {
              ...originalField,
              enum: [...new Set(countryMetadata.countries.map((p) => p.currency))],
            }
          : originalField.country_tax_identifier
            ? {
                ...originalField,
                enum: [
                  ...new Set(countryMetadata.countries.flatMap((p) => p.tax_identifier_kinds)),
                ],
              }
            : originalField;
      const array = field.type.startsWith("[]");
      const base = array ? field.type.slice(2) : field.type;
      let goType = base === "uuid" ? "uuid.UUID" : base;
      if (array) goType = "[]" + goType;
      if (field.pointer || field.optional) goType = "*" + goType;
      const validation = [];
      if (
        !field.optional &&
        ((base === "string" && field.min > 0) ||
          base === "uuid" ||
          array ||
          field.pointer ||
          field.nonzero)
      )
        validation.push("required");
      if (field.optional) validation.push("omitempty");
      if (field.min !== undefined) validation.push(`min=${field.min}`);
      if (field.max !== undefined) validation.push(`max=${field.max}`);
      if (array) validation.push("dive");
      if (field.enum) validation.push(`required,oneof=${field.enum.join(" ")}`);
      if (field.format === "optional_email") validation.push("omitempty,email");
      const tags = [`json:"${field.name}"`];
      if (validation.length) tags.push(`binding:"${validation.join(",")}"`);
      if (field.gorm) tags.push(`gorm:"${field.gorm}"`);
      go += `${pascal(field.name)} ${goType} \`${tags.join(" ")}\`\n`;
      let schema =
        names[base] ??
        (base === "uuid" ? "identifier" : base === "string" ? "z.string()" : "z.number().int()");
      if (field.uuid_any)
        schema =
          'z.string().uuid().refine(value=>value!=="00000000-0000-0000-0000-000000000000","Choose a valid hospital reference.")';
      if (field.enum) schema = `z.enum(${JSON.stringify(field.enum)})`;
      if (array) schema = `z.array(${schema})`;
      if (field.trim) schema += ".trim()";
      if (field.upper) schema += ".toUpperCase()";
      if (field.min !== undefined) schema += `.min(${field.min})`;
      if (field.max !== undefined) schema += `.max(${field.max})`;
      if (field.pattern)
        schema += `.regex(new RegExp(${JSON.stringify(field.pattern)}),"Use the required format.")`;
      if (field.format === "optional_email")
        schema += `.refine(value=>value === "" || z.string().email().safeParse(value).success,"Use a valid email address.")`;
      if (field.format === "optional_https")
        schema += `.refine(value=>{if(value === "")return true;try{const u=new URL(value);return u.protocol === "https:" && u.hostname !== "" && u.username === "" && u.password === "" && u.hash === ""}catch{return false}},"Use an HTTPS website without credentials or a fragment.")`;
      if (field.format === "date") schema += '.date("Use a full valid date.")';
      if (field.format === "datetime")
        schema += '.datetime({offset:true,message:"Use a valid date and time with a timezone."})';
      if (field.unique)
        schema += '.refine(value=>new Set(value).size===value.length,"Choose each value once.")';
      if (field.nonzero) schema += '.refine(value=>value!==0,"Quantity cannot be zero.")';
      if (field.optional) schema += ".nullable().optional()";
      ts += `${field.name}:${schema},\n`;
    }
    if (model.embed) go += `${model.embed}\n`;
    go += "}\n\n";
    ts += "}).strict()";
    if (model.date_order)
      ts += `.refine(value=>Date.parse(value.${model.date_order.end})>Date.parse(value.${model.date_order.start}),{path:[${JSON.stringify(model.date_order.end)}],message:"Expiry must be after the start time."})`;
    if (model.scope_policy) {
      const policy = model.scope_policy;
      const allowedLocation = [...policy.location_optional, ...policy.location_required];
      ts += `.superRefine((value,ctx)=>{if(value.status==="revoked")return;const scoped=value.premise_id!=null;if(scoped&&!${JSON.stringify(allowedLocation)}.includes(value.role))ctx.addIssue({code:"custom",path:["premise_id"],message:"This role requires organisation-wide access."});if(!scoped&&${JSON.stringify(policy.location_required)}.includes(value.role))ctx.addIssue({code:"custom",path:["premise_id"],message:"Choose a warehouse or depot for this role."});})`;
      go += `func valid${model.name}Scope(v ${model.name})bool{if v.Status=="revoked"{return true};if v.PremiseID!=nil{switch v.Role{case ${allowedLocation.map(JSON.stringify).join(",")}:return true};return false};switch v.Role{case ${policy.location_required.map(JSON.stringify).join(",")}:return false};return true}\n`;
      go += `func valid${model.name}PremiseKind(kind string)bool{switch kind{case ${policy.premise_kinds.map(JSON.stringify).join(",")}:return true};return false}\n`;
    }
    ts += ";\n\n";
    if (contract.go_patterns) {
      const fields = model.fields.filter((f) => f.pattern);
      if (fields.length) {
        for (const f of fields)
          go += `var pattern${model.name}${pascal(f.name)}=regexp.MustCompile(${JSON.stringify(f.pattern)})\n`;
        go += `func valid${model.name}Patterns(v ${model.name})bool{return ${fields.map((f) => `pattern${model.name}${pascal(f.name)}.MatchString(v.${pascal(f.name)})`).join(" && ")}}\n`;
      }
    }
  }
  const outputs = {
    [`backend/internal/modules/${moduleName}/input_types.go`]: execFileSync("gofmt", [], {
      input: go,
      encoding: "utf8",
    }),
    [`packages/api/src/${moduleName}-contract.ts`]: execFileSync(
      "pnpm",
      ["exec", "prettier", "--stdin-filepath", `packages/api/src/${moduleName}-contract.ts`],
      { cwd: root, input: ts, encoding: "utf8" },
    ),
  };
  for (const [file, content] of Object.entries(outputs)) {
    if (process.argv.includes("--check")) {
      if ((await readFile(path.join(root, file), "utf8")) !== content)
        throw new Error(`Generated ${moduleName} contract is stale: ${file}`);
    } else await writeFile(path.join(root, file), content);
  }
}
